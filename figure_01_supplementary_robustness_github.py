def compute_trend_map_from_annual(
    annual_da,
    years_subset,
    min_valid_years,
):
    all_years = annual_da.year.values.astype(int)
    years_subset = np.asarray(
        years_subset,
        dtype=int,
    )
    selected = np.isin(
        all_years,
        years_subset,
    )

    years = all_years[selected]
    data = annual_da.sel(
        year=years
    ).values.astype(float)

    ny = data.shape[1]
    nx = data.shape[2]

    slope = np.full(
        (ny, nx),
        np.nan,
        dtype=np.float32,
    )
    pvalue = np.full_like(
        slope,
        np.nan,
    )
    lag1 = np.full_like(
        slope,
        np.nan,
    )
    method = np.full_like(
        slope,
        np.nan,
    )

    for iy in range(ny):
        print(
            f"       temporal trend: latitude {iy + 1}/{ny}"
        )
        for ix in range(nx):
            y = data[:, iy, ix]
            ok = np.isfinite(y)

            if ok.sum() < min_valid_years:
                continue

            (
                sen,
                p,
                _,
                _,
                r1,
                _,
                method_code,
                _,
            ) = robust_trend(
                y[ok],
                years[ok],
                min_valid_years=min_valid_years,
            )

            slope[iy, ix] = sen
            pvalue[iy, ix] = p
            lag1[iy, ix] = r1
            method[iy, ix] = method_code

    return slope, pvalue, lag1, method


