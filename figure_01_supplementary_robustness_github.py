def detect_runs_1d(mask, intensity, years, min_len):
    annual_freq = {
        int(y): 0.0
        for y in range(START_YEAR, END_YEAR + 1)
    }
    annual_days = {
        int(y): 0.0
        for y in range(START_YEAR, END_YEAR + 1)
    }
    annual_intensity = {
        int(y): 0.0
        for y in range(START_YEAR, END_YEAR + 1)
    }

    n = len(mask)
    i = 0

    while i < n:
        if mask[i]:
            j = i
            while j + 1 < n and mask[j + 1]:
                j += 1

            duration = j - i + 1

            if duration >= min_len:
                start_year = int(years[i])
                if START_YEAR <= start_year <= END_YEAR:
                    annual_freq[start_year] += 1.0

                for k in range(i, j + 1):
                    year = int(years[k])
                    if START_YEAR <= year <= END_YEAR:
                        annual_days[year] += 1.0
                        value = intensity[k]
                        if np.isfinite(value) and value > 0:
                            annual_intensity[year] += float(value)

            i = j + 1
        else:
            i += 1

    return annual_freq, annual_days, annual_intensity


def z_pos(value, clim_mean, clim_std):
    std = np.where(
        clim_std <= 1e-6,
        np.nan,
        clim_std,
    )
    z = (value - clim_mean) / std
    z = np.clip(z, Z_CLIP_MIN, Z_CLIP_MAX)
    return np.where(
        z > 0,
        z,
        0.0,
    ).astype(np.float32)


def variable_row(ds, varname, iy):
    return (
        ds[varname]
        .isel(lat=iy)
        .transpose("time", "lon")
        .values
        .astype(np.float32, copy=False)
    )


def threshold_row(ds_thr, varname, ds_daily, iy):
    return (
        ds_thr[varname]
        .sel(doy_noleap=ds_daily["doy_noleap"])
        .isel(lat=iy)
        .transpose("time", "lon")
        .values
        .astype(np.float32, copy=False)
    )


def compute_doy_quantile(
    base,
    varname,
    percentile,
    brazil_mask,
    outname,
):
    print(f"[INFO] Computing {outname}: P{percentile}")

    base_var = base[varname].where(brazil_mask)
    half = ROLLING_WINDOW_DAYS // 2
    output = []

    for doy in range(1, 366):
        window = [
            (doy + offset - 1) % 365 + 1
            for offset in range(-half, half + 1)
        ]

        subset = base_var.where(
            base["doy_noleap"].isin(window),
            drop=True,
        )

        threshold = subset.quantile(
            percentile / 100.0,
            dim="time",
            skipna=True,
        )
        threshold = threshold.drop_vars(
            "quantile",
            errors="ignore",
        )
        output.append(threshold)

    da = xr.concat(
        output,
        dim="doy_noleap",
    )
    da = da.assign_coords(
        doy_noleap=np.arange(
            1,
            366,
            dtype=np.int16,
        )
    )
    da.name = outname
    return da


