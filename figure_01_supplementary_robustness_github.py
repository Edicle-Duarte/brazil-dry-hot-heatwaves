def compute_sensitivity_scenario(
    ds_daily,
    ds_thr,
    brazil_mask,
    cfg,
    output_dir,
):
    scenario = cfg["scenario"]
    min_len = int(cfg["min_len"])
    dhw_vpd_percentile = float(
        cfg["dhw_vpd_percentile"]
    )
    hhw_twb_percentile = float(
        cfg["hhw_twb_percentile"]
    )

    print(f"[INFO] Computing sensitivity: {scenario}")

    dhw_vpd_name = (
        "DHW_VPDmean_P75"
        if dhw_vpd_percentile == 75.0
        else f"DHW_VPDmean_P{int(dhw_vpd_percentile)}"
    )
    hhw_twb_name = (
        "HHW_Twbmax_P95"
        if hhw_twb_percentile == 95.0
        else f"HHW_Twbmax_P{int(hhw_twb_percentile)}"
    )

    time = pd.to_datetime(ds_daily.time.values)
    years = np.asarray(
        [timestamp.year for timestamp in time],
        dtype=np.int16,
    )
    year_axis = np.arange(
        START_YEAR,
        END_YEAR + 1,
        dtype=np.int16,
    )
    year_indices = {
        int(year): np.where(years == year)[0]
        for year in year_axis
    }

    lats = ds_daily.lat.values
    lons = ds_daily.lon.values
    ny = len(lats)
    nx = len(lons)
    mask_np = brazil_mask.values.astype(bool)

    output_arrays = {}
    for kind in ("HHW", "DHW"):
        for suffix in (
            "trend_decade",
            "pvalue",
            "lag1_autocorr_detrended",
            "lag1_critical",
            "MK_method_code",
            "original_MK_pvalue",
        ):
            output_arrays[
                f"{kind}_TmaxOnly_intensity_{suffix}"
            ] = np.full(
                (ny, nx),
                np.nan,
                dtype=np.float32,
            )

    for iy in range(ny):
        print(
            f"       {scenario}: latitude {iy + 1}/{ny}"
        )

        valid_lon_idx = np.where(
            mask_np[iy, :]
        )[0]
        if valid_lon_idx.size == 0:
            continue

        Tmax = variable_row(
            ds_daily,
            "Tmax",
            iy,
        )
        Twbmax = variable_row(
            ds_daily,
            "Twbmax",
            iy,
        )
        VPD = variable_row(
            ds_daily,
            "VPDmean",
            iy,
        )

        HHW_Twb_thr = threshold_row(
            ds_thr,
            hhw_twb_name,
            ds_daily,
            iy,
        )
        DHW_Tmax_thr = threshold_row(
            ds_thr,
            "DHW_Tmax_P95",
            ds_daily,
            iy,
        )
        DHW_VPD_thr = threshold_row(
            ds_thr,
            dhw_vpd_name,
            ds_daily,
            iy,
        )

        CLIM_Tmax_mean = threshold_row(
            ds_thr,
            "CLIM_Tmax_mean",
            ds_daily,
            iy,
        )
        CLIM_Tmax_std = threshold_row(
            ds_thr,
            "CLIM_Tmax_std",
            ds_daily,
            iy,
        )

        z_tmax = z_pos(
            Tmax,
            CLIM_Tmax_mean,
            CLIM_Tmax_std,
        )

        flags = {
            "HHW": Twbmax >= HHW_Twb_thr,
            "DHW": (
                (Tmax >= DHW_Tmax_thr)
                & (VPD >= DHW_VPD_thr)
            ),
        }

        validity = {
            "HHW": (
                np.isfinite(Twbmax)
                & np.isfinite(HHW_Twb_thr)
                & np.isfinite(Tmax)
                & np.isfinite(CLIM_Tmax_mean)
                & np.isfinite(CLIM_Tmax_std)
                & np.isfinite(z_tmax)
            ),
            "DHW": (
                np.isfinite(Tmax)
                & np.isfinite(VPD)
                & np.isfinite(DHW_Tmax_thr)
                & np.isfinite(DHW_VPD_thr)
                & np.isfinite(CLIM_Tmax_mean)
                & np.isfinite(CLIM_Tmax_std)
                & np.isfinite(z_tmax)
            ),
        }

        for ix in valid_lon_idx:
            for kind in ("HHW", "DHW"):
                valid_cell = validity[kind][:, ix]

                valid_by_year = {
                    int(year): int(
                        np.sum(
                            valid_cell[
                                year_indices[int(year)]
                            ]
                        )
                    )
                    for year in year_axis
                }

                if (
                    sum(
                        n >= MIN_VALID_DAYS_PER_YEAR
                        for n in valid_by_year.values()
                    )
                    < MIN_VALID_YEARS_FOR_TREND
                ):
                    continue

                event_mask = np.where(
                    valid_cell,
                    flags[kind][:, ix],
                    False,
                )

                _, _, annual_intensity = detect_runs_1d(
                    event_mask,
                    z_tmax[:, ix],
                    years,
                    min_len=min_len,
                )

                series = np.array(
                    [
                        annual_intensity[int(year)]
                        if valid_by_year[int(year)]
                        >= MIN_VALID_DAYS_PER_YEAR
                        else np.nan
                        for year in year_axis
                    ],
                    dtype=np.float32,
                )

                (
                    slope,
                    pvalue,
                    _,
                    _,
                    lag1,
                    lag1_critical,
                    method_code,
                    original_p,
                ) = robust_trend(
                    series,
                    year_axis,
                )

                base = (
                    f"{kind}_TmaxOnly_intensity"
                )
                output_arrays[
                    f"{base}_trend_decade"
                ][iy, ix] = slope
                output_arrays[
                    f"{base}_pvalue"
                ][iy, ix] = pvalue
                output_arrays[
                    f"{base}_lag1_autocorr_detrended"
                ][iy, ix] = lag1
                output_arrays[
                    f"{base}_lag1_critical"
                ][iy, ix] = lag1_critical
                output_arrays[
                    f"{base}_MK_method_code"
                ][iy, ix] = method_code
                output_arrays[
                    f"{base}_original_MK_pvalue"
                ][iy, ix] = original_p

    ds_out = xr.Dataset(
        {
            name: (("lat", "lon"), values)
            for name, values in output_arrays.items()
        },
        coords={
            "lat": lats,
            "lon": lons,
        },
        attrs={
            "scenario": scenario,
            "description": cfg["description"],
            "minimum_event_length_days": min_len,
            "DHW_VPD_percentile": dhw_vpd_percentile,
            "HHW_Twbmax_percentile": hhw_twb_percentile,
            "comparison_intensity": (
                "common Tmax-only standardized severity"
            ),
            "trend_method": "Theil-Sen median slope per decade",
            "significance_test": (
                "Original MK unless detrended lag-1 rank autocorrelation "
                "is significant; Hamed-Rao MK lag1 otherwise"
            ),
            "trend_significance_version": TREND_SIGNIFICANCE_VERSION,
            "baseline": f"{BASE_START}-{BASE_END}",
        },
    )

    ds_out[
        "DHW_minus_HHW_TmaxOnly_intensity_trend_decade"
    ] = (
        ds_out[
            "DHW_TmaxOnly_intensity_trend_decade"
        ]
        - ds_out[
            "HHW_TmaxOnly_intensity_trend_decade"
        ]
    ).astype("float32")

    ds_out[
        "DHW_minus_HHW_TmaxOnly_intensity_trend_decade"
    ].attrs.update({
        "units": "standardized severity decade-1",
        "definition": (
            "DHW_TmaxOnly_intensity_trend_decade - "
            "HHW_TmaxOnly_intensity_trend_decade"
        ),
    })

    out_file = sensitivity_file(
        output_dir,
        scenario,
    )

    safe_to_netcdf(
        ds_out,
        out_file,
        encoding={
            var: {
                "zlib": True,
                "complevel": 4,
                "dtype": "float32",
            }
            for var in ds_out.data_vars
        },
    )
    print(f"[OK] Saved sensitivity: {out_file}")
    return ds_out


