def main():
    warnings.filterwarnings("ignore")

    args = parse_args()
    paths = configure_paths(args)

    print("=" * 82)
    print("FIGURE 01 — SUPPLEMENTARY ROBUSTNESS S1–S4")
    print("=" * 82)
    print(f"Figure 01 root : {paths['root']}")
    print(f"Output          : {paths['output']}")
    print("S2/S3 contrast : common Tmax-only standardized severity")
    print(
        "Significance   : original MK unless significant detrended lag-1; "
        "Hamed-Rao lag1 otherwise"
    )
    print("=" * 82)

    trends = safe_open_dataset(
        paths["trends"],
        decode_times=False,
        chunks=None,
    )
    annual = safe_open_dataset(
        paths["annual"],
        decode_times=False,
        chunks=None,
    )
    ds_thr = safe_open_dataset(
        paths["thresholds"],
        decode_times=False,
        chunks=None,
    )

    # Fail early when the Figure 01 trend file lacks required common-scale fields.
    required_corrected = {
        "HHW_TmaxOnly_intensity_trend_decade",
        "DHW_TmaxOnly_intensity_trend_decade",
        "DHW_minus_HHW_TmaxOnly_intensity_trend_decade",
    }

    if not required_corrected.issubset(
        set(trends.data_vars)
    ):
        raise RuntimeError(
            "The supplied Figure 01 trend file is not the corrected version. "
            "Missing common Tmax-only HHW/DHW fields."
        )

    lats = trends.lat.values
    lons = trends.lon.values

    brazil_mask = make_brazil_mask(
        lats,
        lons,
        paths["brazil_shp"],
    )
    region_masks = build_region_masks(
        lats,
        lons,
        brazil_mask,
        paths["biomes_shp"],
    )
    weights = area_weights_for_grid(
        lats,
        lons,
    )

    # S1 is generated from the main Figure 01 trends.
    make_s1(
        trends,
        region_masks,
        weights,
        paths["output"],
    )

    # S2 always regenerated from common-scale contrast.
    make_s2(
        trends,
        region_masks,
        weights,
        paths["output"],
    )

    # S4 uses primary DHW intensity and the Figure 01 significance framework.
    s4_ds, _ = make_s4(
        annual,
        trends,
        region_masks,
        weights,
        paths["output"],
        args.recompute_s4,
    )

    # S3 sensitivity.
    nonprimary = [
        cfg
        for cfg in SENSITIVITY_SCENARIOS
        if not cfg["compute_from_main"]
    ]

    scenario_datasets = {}

    need_daily = any(
        args.recompute_sensitivities
        or not cache_is_compatible(
            sensitivity_file(
                paths["output"],
                cfg["scenario"],
            ),
            cfg["scenario"],
        )
        for cfg in nonprimary
    )

    ds_daily = None

    if need_daily:
        ds_daily = open_daily_files(
            paths["daily_dir"]
        )

        # Align the daily fields with the Figure 01 grid.
        ds_daily = ds_daily.sel(
            lat=trends.lat,
            lon=trends.lon,
        )

        ds_thr = ensure_sensitivity_thresholds(
            ds_daily,
            ds_thr,
            brazil_mask,
            paths["output"],
        )

    for cfg in nonprimary:
        cache = sensitivity_file(
            paths["output"],
            cfg["scenario"],
        )

        if (
            not args.recompute_sensitivities
            and cache_is_compatible(
                cache,
                cfg["scenario"],
            )
        ):
            print(
                f"[INFO] Loading compatible sensitivity cache: {cache.name}"
            )
            scenario_datasets[
                cfg["scenario"]
            ] = safe_open_dataset(
                cache,
                decode_times=False,
                chunks=None,
            )
        else:
            scenario_datasets[
                cfg["scenario"]
            ] = compute_sensitivity_scenario(
                ds_daily,
                ds_thr,
                brazil_mask,
                cfg,
                paths["output"],
            )

    make_s3(
        trends,
        scenario_datasets,
        region_masks,
        weights,
        paths["output"],
    )

    make_sensitivity_detail_table(
        trends,
        scenario_datasets,
        region_masks,
        weights,
        paths["output"],
    )

    readme = (
        paths["output"]
        / "README_figure_01_supplementary_robustness.txt"
    )

    readme.write_text(
        "\n".join([
            "Figure 01 supplementary robustness outputs",
            "==========================================",
            "",
            "S1 — Figure 01 primary regime summaries.",
            "     Primary regime-specific intensity units are retained.",
            "",
            "S2 — Primary HHW-DHW contrast.",
            "     Uses DHW_minus_HHW_TmaxOnly_intensity_trend_decade.",
            "",
            "S3 — Sensitivity of the HHW-DHW contrast.",
            "     Every scenario compares HHW and DHW using common Tmax-only",
            "     standardized severity.",
            "",
            "S4 — Temporal robustness of PRIMARY DHW intensity.",
            "     DHW primary intensity remains 0.5*z+(Tmax)+0.5*z+(VPD).",
            "",
            "Significance methodology:",
            TREND_SIGNIFICANCE_VERSION,
            "",
            "Important: direct subtraction of primary DHW and HHW intensity",
            "fields is not used anywhere in S2 or S3.",
        ]),
        encoding="utf-8",
    )

    trends.close()
    annual.close()
    ds_thr.close()

    if ds_daily is not None:
        ds_daily.close()

    try:
        s4_ds.close()
    except Exception:
        pass

    for ds in scenario_datasets.values():
        try:
            ds.close()
        except Exception:
            pass

    print("[DONE] Supplementary Tables S1–S4 generated.")


if __name__ == "__main__":
    main()
