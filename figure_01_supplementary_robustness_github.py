def remove_feb29(ds):
    mask = ~((ds.time.dt.month == 2) & (ds.time.dt.day == 29))
    return ds.sel(time=mask)


def ensure_complete_daily_calendar(ds):
    expected = pd.date_range(
        f"{START_YEAR}-01-01",
        f"{END_YEAR}-12-31",
        freq="1D",
    )
    return ds.reindex(time=expected)


def add_noleap_doy(ds):
    dates = pd.to_datetime(ds.time.values)
    doy = []
    for d in dates:
        y0 = pd.Timestamp(f"{d.year}-01-01")
        val = (d - y0).days + 1
        if d.is_leap_year and d.month > 2:
            val -= 1
        doy.append(val)
    return ds.assign_coords(
        doy_noleap=("time", np.asarray(doy, dtype=np.int16))
    )


def normalize_text(x):
    if pd.isna(x):
        return ""
    s = unicodedata.normalize("NFKD", str(x).strip())
    s = "".join(ch for ch in s if not unicodedata.combining(ch))
    return re.sub(r"\s+", " ", s).upper()


def detect_biome_name_column(gdf):
    for col in ["Bioma", "BIOMA", "bioma", "NOME", "nome", "NAME", "name"]:
        if col in gdf.columns:
            return col
    for col in gdf.columns:
        if col != "geometry" and str(gdf[col].dtype) == "object":
            return col
    raise ValueError(f"Could not identify biome-name column: {list(gdf.columns)}")


def make_brazil_mask(lats, lons, shp_path):
    uf = gpd.read_file(shp_path).to_crs(epsg=4326)
    geom = uf.dissolve().geometry.iloc[0]
    mask = np.zeros((len(lats), len(lons)), dtype=bool)

    for iy, lat in enumerate(lats):
        points = [Point(float(lon), float(lat)) for lon in lons]
        mask[iy, :] = [
            geom.contains(point) or geom.touches(point)
            for point in points
        ]

    return xr.DataArray(
        mask,
        coords={"lat": lats, "lon": lons},
        dims=("lat", "lon"),
    )


def build_region_masks(lats, lons, brazil_mask, biomes_shp):
    masks = {"Brazil": brazil_mask.astype(bool)}

    if biomes_shp is None:
        return masks
    if not biomes_shp.exists():
        print(f"[WARN] Biomes shapefile not found: {biomes_shp}")
        return masks

    biomes = gpd.read_file(biomes_shp).to_crs(epsg=4326)
    name_col = detect_biome_name_column(biomes)

    lon2d, lat2d = np.meshgrid(lons, lats)
    flat_points = [
        Point(float(x), float(y))
        for x, y in zip(lon2d.ravel(), lat2d.ravel())
    ]

    display_map = {
        "AMAZONIA": "Amazon",
        "AMAZON": "Amazon",
        "CERRADO": "Cerrado",
        "CAATINGA": "Caatinga",
        "MATA ATLANTICA": "Atlantic Forest",
        "ATLANTIC FOREST": "Atlantic Forest",
        "PANTANAL": "Pantanal",
        "PAMPA": "Pampa",
        "PAMPAS": "Pampa",
    }

    for raw_name, sub in biomes.groupby(name_col):
        display = display_map.get(normalize_text(raw_name), str(raw_name))
        geom = sub.dissolve().geometry.iloc[0]
        values = np.array(
            [
                geom.contains(point) or geom.touches(point)
                for point in flat_points
            ],
            dtype=bool,
        ).reshape(len(lats), len(lons))

        values &= brazil_mask.values.astype(bool)

        if values.sum() > 0:
            masks[display] = xr.DataArray(
                values,
                coords={"lat": lats, "lon": lons},
                dims=("lat", "lon"),
            )

    return masks


