def _available_netcdf_engines():
    engines = xr.backends.list_engines()
    return [name for name in ("h5netcdf", "netcdf4", "scipy") if name in engines]


def safe_open_dataset(path, *, decode_times=True, chunks=None, **kwargs):
    errors = []
    for engine in _available_netcdf_engines():
        try:
            return xr.open_dataset(
                path,
                engine=engine,
                decode_times=decode_times,
                chunks=chunks,
                **kwargs,
            )
        except Exception as exc:
            errors.append(f"{engine}: {type(exc).__name__}: {exc}")

    raise RuntimeError(
        f"Could not open NetCDF file: {path}\n"
        + "\n".join(errors)
    )


def safe_to_netcdf(ds, path, *, encoding=None, **kwargs):
    errors = []
    engines = _available_netcdf_engines()

    if "h5netcdf" in engines:
        try:
            return ds.to_netcdf(
                path,
                engine="h5netcdf",
                encoding=encoding,
                **kwargs,
            )
        except Exception as exc:
            errors.append(f"h5netcdf: {type(exc).__name__}: {exc}")

    if "netcdf4" in engines:
        try:
            return ds.to_netcdf(
                path,
                engine="netcdf4",
                encoding=encoding,
                **kwargs,
            )
        except Exception as exc:
            errors.append(f"netcdf4: {type(exc).__name__}: {exc}")

    if "scipy" in engines:
        scipy_encoding = None
        if encoding:
            scipy_encoding = {
                var: {
                    k: v
                    for k, v in opts.items()
                    if k in {"dtype", "_FillValue", "scale_factor", "add_offset"}
                }
                for var, opts in encoding.items()
            }
        try:
            return ds.to_netcdf(
                path,
                engine="scipy",
                encoding=scipy_encoding,
                **kwargs,
            )
        except Exception as exc:
            errors.append(f"scipy: {type(exc).__name__}: {exc}")

    raise RuntimeError(
        f"Could not write NetCDF file: {path}\n"
        + "\n".join(errors)
    )


