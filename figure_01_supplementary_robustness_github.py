def make_sensitivity_detail_table(
    main_trends,
    scenario_datasets,
    region_masks,
    weights,
    output_dir,
):
    rows = []

    for cfg in SENSITIVITY_SCENARIOS:
        scenario = cfg["scenario"]

        if cfg["compute_from_main"]:
            ds = primary_sensitivity_dataset(
                main_trends
            )
        else:
            ds = scenario_datasets[scenario]

        for kind in ("HHW", "DHW"):
            var = (
                f"{kind}_TmaxOnly_intensity_trend_decade"
            )
            pvar = (
                f"{kind}_TmaxOnly_intensity_pvalue"
            )

            rows.extend(
                summarize_map(
                    ds[var],
                    ds[pvar],
                    region_masks,
                    weights,
                    scenario=scenario,
                    kind=kind,
                    metric="TmaxOnly_intensity",
                    units="standardized severity decade-1",
                    significance_field=pvar,
                )
            )

    df = pd.DataFrame(rows)

    path = (
        output_dir
        / "Diagnostic_Table_threshold_duration_sensitivity_all_metrics.csv"
    )
    df.to_csv(path, index=False)
    print(f"[OK] Saved diagnostic table: {path}")


