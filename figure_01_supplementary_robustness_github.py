def weighted_quantile(values, weights, q):
    values = np.asarray(values, dtype=float)
    weights = np.asarray(weights, dtype=float)

    ok = np.isfinite(values) & np.isfinite(weights) & (weights > 0)
    if ok.sum() == 0:
        return np.nan

    values = values[ok]
    weights = weights[ok]
    idx = np.argsort(values)
    values = values[idx]
    weights = weights[idx]

    cdf = np.cumsum(weights) / np.sum(weights)
    return float(np.interp(q, cdf, values))


def summarize_map(
    values_da,
    p_da,
    region_masks,
    weights_da,
    *,
    scenario,
    kind,
    metric,
    units,
    significance_field=None,
):
    rows = []

    for region, mask_da in region_masks.items():
        vals = values_da.where(mask_da).values.ravel()
        weights = weights_da.where(mask_da).values.ravel()

        if p_da is None:
            pvals = np.full(vals.shape, np.nan, dtype=float)
        else:
            pvals = p_da.where(mask_da).values.ravel()

        ok = np.isfinite(vals) & np.isfinite(weights) & (weights > 0)
        if ok.sum() == 0:
            continue

        vals = vals[ok]
        weights = weights[ok]
        pvals = pvals[ok]

        pos = vals > 0
        neg = vals < 0
        sig = np.isfinite(pvals) & (pvals <= P_THRESHOLD)

        q25 = weighted_quantile(vals, weights, 0.25)
        med = weighted_quantile(vals, weights, 0.50)
        q75 = weighted_quantile(vals, weights, 0.75)

        rows.append({
            "scenario": scenario,
            "region": region,
            "kind": kind,
            "metric": metric,
            "units": units,
            "significance_field": significance_field or "",
            "n_grid_cells": int(ok.sum()),
            "trend_median": med,
            "trend_q25": q25,
            "trend_q75": q75,
            "trend_iqr": q75 - q25,
            "area_positive_percent": float(
                100.0 * np.sum(weights[pos]) / np.sum(weights)
            ),
            "area_negative_percent": float(
                100.0 * np.sum(weights[neg]) / np.sum(weights)
            ),
            "area_significant_percent": float(
                100.0 * np.sum(weights[sig]) / np.sum(weights)
            ) if p_da is not None else np.nan,
            "area_significant_positive_percent": float(
                100.0 * np.sum(weights[sig & pos]) / np.sum(weights)
            ) if p_da is not None else np.nan,
            "area_significant_negative_percent": float(
                100.0 * np.sum(weights[sig & neg]) / np.sum(weights)
            ) if p_da is not None else np.nan,
        })

    return rows


