def _mk_score_and_variance(y):
    y = np.asarray(y, dtype=float)
    y = y[np.isfinite(y)]
    n = len(y)

    if n < MIN_VALID_YEARS_FOR_TREND:
        return np.nan, np.nan

    s = sum(
        np.sign(y[j] - y[i])
        for i in range(n - 1)
        for j in range(i + 1, n)
    )

    _, counts = np.unique(y, return_counts=True)
    tie_term = sum(
        c * (c - 1) * (2 * c + 5)
        for c in counts
    )
    var_s = (
        n * (n - 1) * (2 * n + 5) - tie_term
    ) / 18.0

    return float(s), float(var_s)


def _mk_p_from_s_var(s, var_s):
    if not np.isfinite(s) or not np.isfinite(var_s) or var_s <= 0:
        return np.nan

    z = (
        (s - np.sign(s)) / np.sqrt(var_s)
        if s != 0 else 0.0
    )
    return float(
        2.0 * (1.0 - norm.cdf(abs(z)))
    )


def mann_kendall_pvalue(y, min_valid_years=MIN_VALID_YEARS_FOR_TREND):
    y = np.asarray(y, dtype=float)
    y = y[np.isfinite(y)]

    if len(y) < min_valid_years:
        return np.nan

    if _HAS_PYMK:
        try:
            return float(mk.original_test(y).p)
        except Exception:
            pass

    # Local calculation needs the same minimum criterion.
    n = len(y)
    s = sum(
        np.sign(y[j] - y[i])
        for i in range(n - 1)
        for j in range(i + 1, n)
    )
    _, counts = np.unique(y, return_counts=True)
    tie_term = sum(
        c * (c - 1) * (2 * c + 5)
        for c in counts
    )
    var_s = (
        n * (n - 1) * (2 * n + 5) - tie_term
    ) / 18.0

    return _mk_p_from_s_var(float(s), float(var_s))


def detrended_lag1_autocorrelation(
    y,
    years,
    alpha=AUTOCORR_ALPHA,
    min_valid_years=MIN_VALID_YEARS_FOR_TREND,
):
    y = np.asarray(y, dtype=float)
    years = np.asarray(years, dtype=float)

    valid = np.isfinite(y) & np.isfinite(years)
    y = y[valid]
    years = years[valid]
    n = len(y)

    if n < min_valid_years or n < 4:
        return np.nan, np.nan, False

    critical = float(
        norm.ppf(1.0 - alpha / 2.0) / np.sqrt(n)
    )

    if np.nanstd(y) <= 1e-12:
        return 0.0, critical, False

    sen = theilslopes(y, years, alpha=0.05)
    slope, intercept = float(sen[0]), float(sen[1])
    residual = y - (intercept + slope * years)

    ranks = (
        pd.Series(residual)
        .rank(method="average")
        .to_numpy(dtype=float)
    )

    if (
        np.nanstd(ranks[:-1]) <= 1e-12
        or np.nanstd(ranks[1:]) <= 1e-12
    ):
        r1 = 0.0
    else:
        r1 = float(
            np.corrcoef(ranks[:-1], ranks[1:])[0, 1]
        )

    significant = bool(
        np.isfinite(r1) and abs(r1) > critical
    )

    return r1, critical, significant


def hamed_rao_mk_pvalue_lag1(
    y,
    years,
    alpha=AUTOCORR_ALPHA,
    min_valid_years=MIN_VALID_YEARS_FOR_TREND,
):
    y = np.asarray(y, dtype=float)
    years = np.asarray(years, dtype=float)

    valid = np.isfinite(y) & np.isfinite(years)
    y = y[valid]
    years = years[valid]
    n = len(y)

    if n < min_valid_years:
        return np.nan

    if _HAS_PYMK:
        try:
            return float(
                mk.hamed_rao_modification_test(
                    y,
                    alpha=alpha,
                    lag=1,
                ).p
            )
        except Exception:
            pass

    # MK S and base variance for available years.
    s = sum(
        np.sign(y[j] - y[i])
        for i in range(n - 1)
        for j in range(i + 1, n)
    )
    _, counts = np.unique(y, return_counts=True)
    tie_term = sum(
        c * (c - 1) * (2 * c + 5)
        for c in counts
    )
    var_s = (
        n * (n - 1) * (2 * n + 5) - tie_term
    ) / 18.0

    if var_s <= 0:
        return np.nan

    sen = theilslopes(y, years, alpha=0.05)
    slope, intercept = float(sen[0]), float(sen[1])
    detrended = y - (intercept + slope * years)

    ranks = (
        pd.Series(detrended)
        .rank(method="average")
        .to_numpy(dtype=float)
    )

    if (
        np.std(ranks[:-1]) <= 1e-12
        or np.std(ranks[1:]) <= 1e-12
    ):
        rho1 = 0.0
    else:
        rho1 = float(
            np.corrcoef(ranks[:-1], ranks[1:])[0, 1]
        )

    critical = float(
        norm.ppf(1.0 - alpha / 2.0) / np.sqrt(n)
    )

    if abs(rho1) <= critical:
        return _mk_p_from_s_var(float(s), float(var_s))

    correction = 1.0 + (
        2.0 * (n - 3) / n
    ) * abs(rho1)
    correction = max(correction, 1.0)

    return _mk_p_from_s_var(
        float(s),
        float(var_s * correction),
    )


def robust_trend(
    y,
    years,
    min_valid_years=MIN_VALID_YEARS_FOR_TREND,
):
    y = np.asarray(y, dtype=float)
    years = np.asarray(years, dtype=float)

    valid = np.isfinite(y) & np.isfinite(years)
    y_valid = y[valid]
    years_valid = years[valid]

    if len(y_valid) < min_valid_years:
        return (
            np.nan, np.nan, np.nan, np.nan,
            np.nan, np.nan, np.nan, np.nan,
        )

    sen = theilslopes(y_valid, years_valid, alpha=0.05)
    sen_slope = float(sen[0] * 10.0)

    original_p = mann_kendall_pvalue(
        y_valid,
        min_valid_years=min_valid_years,
    )

    lag1_r, lag1_critical, lag1_sig = (
        detrended_lag1_autocorrelation(
            y_valid,
            years_valid,
            min_valid_years=min_valid_years,
        )
    )

    if lag1_sig:
        selected_p = hamed_rao_mk_pvalue_lag1(
            y_valid,
            years_valid,
            min_valid_years=min_valid_years,
        )
        method_code = 1.0
    else:
        selected_p = original_p
        method_code = 0.0

    lr = linregress(years_valid, y_valid)
    ols_slope = float(lr.slope * 10.0)
    ols_p = float(lr.pvalue)

    return (
        sen_slope,
        selected_p,
        ols_slope,
        ols_p,
        lag1_r,
        lag1_critical,
        method_code,
        original_p,
    )


