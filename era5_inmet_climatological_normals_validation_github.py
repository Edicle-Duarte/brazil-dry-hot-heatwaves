def standardize_lat_lon_time(ds: xr.Dataset) -> xr.Dataset:
    rename = {}
    for t in ["time", "valid_time", "datetime", "date"]:
        if t in ds.coords or t in ds.dims:
            if t != "time": rename[t] = "time"
            break
    for la in ["latitude", "lat", "LAT", "Latitude", "y"]:
        if la in ds.coords or la in ds.dims:
            if la != "lat": rename[la] = "lat"
            break
    for lo in ["longitude", "lon", "LON", "Longitude", "x"]:
        if lo in ds.coords or lo in ds.dims:
            if lo != "lon": rename[lo] = "lon"
            break
    if rename:
        ds = ds.rename(rename)
    if "time" not in ds.coords or "lat" not in ds.coords or "lon" not in ds.coords:
        raise ValueError(f"ERA5 dataset missing required coordinates. Coords: {list(ds.coords)}")
    ds["time"] = pd.to_datetime(ds["time"].values)
    if float(ds["lon"].max()) > 180:
        ds = ds.assign_coords(lon=((ds["lon"] + 180) % 360) - 180).sortby("lon")
    if ds["lat"].values[0] > ds["lat"].values[-1]:
        ds = ds.sortby("lat")
    return ds


def find_variable(ds: xr.Dataset, candidates: List[str], required: bool = True) -> Optional[str]:
    lower = {v.lower(): v for v in ds.data_vars}
    norm = {normalize_name(v): v for v in ds.data_vars}
    for c in candidates:
        if c in ds.data_vars:
            return c
        if c.lower() in lower:
            return lower[c.lower()]
        nc = normalize_name(c)
        if nc in norm:
            return norm[nc]
    for c in candidates:
        nc = normalize_name(c)
        for nv, original in norm.items():
            if nc and (nc in nv or nv in nc):
                return original
    if required:
        raise ValueError(f"Could not find ERA5 variable among {candidates}. Available: {list(ds.data_vars)}")
    return None


def reduce_to_time_lat_lon(da: xr.DataArray) -> xr.DataArray:
    keep = {"time", "lat", "lon"}
    for dim in list(da.dims):
        if dim not in keep:
            if da.sizes[dim] == 1:
                da = da.isel({dim: 0})
            else:
                da = da.mean(dim=dim, skipna=True)
    return da


def maybe_kelvin_to_celsius(da: xr.DataArray) -> xr.DataArray:
    med = float(np.nanmedian(da.values))
    if np.isfinite(med) and med > 100:
        return da - 273.15
    return da


def saturation_vapour_pressure_hpa(temp_c):
    return 6.112 * np.exp((17.67 * temp_c) / (temp_c + 243.5))


def compute_rh_percent(t_c, td_c):
    es = saturation_vapour_pressure_hpa(t_c)
    ea = saturation_vapour_pressure_hpa(td_c)
    return np.clip(100.0 * ea / es, 0.0, 100.0)


def compute_wetbulb_stull(t_c, rh_pct):
    rh = np.clip(rh_pct, 1.0, 100.0)
    tw = (
        t_c * np.arctan(0.151977 * np.sqrt(rh + 8.313659))
        + np.arctan(t_c + rh)
        - np.arctan(rh - 1.676331)
        + 0.00391838 * rh ** 1.5 * np.arctan(0.023101 * rh)
        - 4.686035
    )
    return tw


def resolve_era5_files(pattern: str) -> List[str]:
    files = sorted(glob.glob(pattern))
    selected = []
    for f in files:
        m = re.search(r"(19|20)\d{2}", Path(f).name)
        if m:
            y = int(m.group(0))
            if START_YEAR <= y <= END_YEAR:
                selected.append(f)
        else:
            selected.append(f)
    if not selected:
        raise FileNotFoundError(f"No ERA5 files overlapping {START_YEAR}-{END_YEAR}: {pattern}")
    return selected


def get_station_grid_indices(ds: xr.Dataset, stations: pd.DataFrame) -> pd.DataFrame:
    lats = ds["lat"].values
    lons = ds["lon"].values
    lon2d, lat2d = np.meshgrid(lons, lats)
    tree = cKDTree(np.column_stack([lat2d.ravel(), lon2d.ravel()]))
    rows = []
    for _, st in stations.iterrows():
        dist, flat_idx = tree.query([st["lat"], st["lon"]])
        iy, ix = np.unravel_index(flat_idx, lat2d.shape)
        rows.append({
            "station_id": str(st["station_id"]),
            "uf": st["uf"],
            "region": st.get("region", UF_TO_REGION.get(st["uf"])),
            "lat": float(st["lat"]),
            "lon": float(st["lon"]),
            "iy": int(iy),
            "ix": int(ix),
            "era5_lat": float(lats[iy]),
            "era5_lon": float(lons[ix]),
            "era5_grid_distance_deg": float(dist),
        })
    return pd.DataFrame(rows)


def year_from_path(path: str) -> str:
    m = re.search(r"(19|20)\d{2}", Path(path).name)
    return m.group(0) if m else Path(path).stem


def aggregate_station_monthly_from_hourly(
    time_index: pd.DatetimeIndex,
    station_meta: pd.DataFrame,
    arrays: Dict[str, np.ndarray],
    daily_time_basis: str,
) -> pd.DataFrame:
    """Aggregate hourly station arrays to monthly values.

    arrays must contain 2-D numpy arrays with shape (time, station):
      t_c, td_c, rh, twb, ws
    """
    station_ids = station_meta["station_id"].astype(str).values
    out_frames = []

    if daily_time_basis == "utc":
        groups = [("ALL", station_meta.index.to_numpy(), 0)]
    elif daily_time_basis == "local_by_uf":
        groups = []
        for uf, sub in station_meta.groupby("uf"):
            offset = UF_UTC_OFFSET_HOURS.get(uf, -3)
            groups.append((uf, sub.index.to_numpy(), offset))
    else:
        raise ValueError("daily_time_basis must be 'utc' or 'local_by_uf'")

    for _, idx, offset in groups:
        if len(idx) == 0:
            continue
        local_time = time_index + pd.Timedelta(hours=offset)

        def wide(arr):
            return pd.DataFrame(arr[:, idx], index=local_time, columns=station_ids[idx])

        t = wide(arrays["t_c"])
        td = wide(arrays["td_c"])
        rh = wide(arrays["rh"])
        twb = wide(arrays["twb"])
        ws = wide(arrays["ws"])

        daily = {
            "TMAX": t.resample("D").max(),
            "TMIN": t.resample("D").min(),
            "TORV": td.resample("D").mean(),
            "UR": rh.resample("D").mean(),
            "VENTIN": ws.resample("D").mean(),
            "TMEDUMID": twb.resample("D").mean(),
        }

        for var, df_daily in daily.items():
            monthly = df_daily.resample("MS").mean()
            n_days = df_daily.resample("MS").count()
            long_val = monthly.stack(dropna=False).rename("era5_value").reset_index()
            long_val.columns = ["date", "station_id", "era5_value"]
            long_n = n_days.stack(dropna=False).rename("n_daily_values_era5").reset_index()
            long_n.columns = ["date", "station_id", "n_daily_values_era5"]
            long = long_val.merge(long_n, on=["date", "station_id"], how="left")
            long["variable"] = var
            long["year"] = pd.to_datetime(long["date"]).dt.year
            long["month"] = pd.to_datetime(long["date"]).dt.month
            out_frames.append(long[["station_id", "variable", "year", "month", "era5_value", "n_daily_values_era5"]])

    if not out_frames:
        return pd.DataFrame(columns=["station_id", "variable", "year", "month", "era5_value", "n_daily_values_era5"])
    return pd.concat(out_frames, ignore_index=True)


def process_era5_year(
    file_path: str,
    stations: pd.DataFrame,
    grid_index: Optional[pd.DataFrame],
    daily_time_basis: str,
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    print(f"[INFO] ERA5 hourly file: {Path(file_path).name}")
    ds = xr.open_dataset(file_path)
    ds = standardize_lat_lon_time(ds)
    ds = ds.sel(time=slice(f"{START_YEAR}-01-01", f"{END_YEAR}-12-31"))
    if ds.sizes.get("time", 0) == 0:
        ds.close()
        return pd.DataFrame(), grid_index

    if grid_index is None:
        grid_index = get_station_grid_indices(ds, stations)
        print(f"[INFO] ERA5 nearest grid cells prepared for {len(grid_index)} stations")

    tvar = find_variable(ds, ["t2m", "2t", "T2M", "T2", "var167", "2m_temperature"], True)
    tdvar = find_variable(ds, ["d2m", "2d", "D2M", "var168", "2m_dewpoint_temperature"], True)
    uvar = find_variable(ds, ["u10", "10u", "U10", "var165", "10m_u_component_of_wind"], True)
    vvar = find_variable(ds, ["v10", "10v", "V10", "var166", "10m_v_component_of_wind"], True)
    print(f"[INFO] ERA5 variables: T={tvar}, Td={tdvar}, U={uvar}, V={vvar}")

    station_dim = "station"
    iy = xr.DataArray(grid_index["iy"].to_numpy(), dims=station_dim)
    ix = xr.DataArray(grid_index["ix"].to_numpy(), dims=station_dim)

    t_c = maybe_kelvin_to_celsius(reduce_to_time_lat_lon(ds[tvar])).isel(lat=iy, lon=ix).values.astype(np.float32)
    td_c = maybe_kelvin_to_celsius(reduce_to_time_lat_lon(ds[tdvar])).isel(lat=iy, lon=ix).values.astype(np.float32)
    u = reduce_to_time_lat_lon(ds[uvar]).isel(lat=iy, lon=ix).values.astype(np.float32)
    v = reduce_to_time_lat_lon(ds[vvar]).isel(lat=iy, lon=ix).values.astype(np.float32)
    ws = np.sqrt(u ** 2 + v ** 2).astype(np.float32)
    rh = compute_rh_percent(t_c, td_c).astype(np.float32)
    twb = compute_wetbulb_stull(t_c, rh).astype(np.float32)

    station_meta = grid_index.reset_index(drop=True).copy()
    station_meta.index = np.arange(len(station_meta))
    time_index = pd.DatetimeIndex(pd.to_datetime(ds["time"].values))
    monthly = aggregate_station_monthly_from_hourly(
        time_index=time_index,
        station_meta=station_meta,
        arrays={"t_c": t_c, "td_c": td_c, "rh": rh, "twb": twb, "ws": ws},
        daily_time_basis=daily_time_basis,
    )

    ds.close()
    return monthly, grid_index


def dewpoint_from_t_rh(t_c, rh_pct):
    """Approximate dew-point temperature [°C] from air temperature [°C] and RH [%]."""
    rh = np.clip(np.asarray(rh_pct, dtype=float), 1e-3, 100.0)
    t = np.asarray(t_c, dtype=float)
    gamma = np.log(rh / 100.0) + (17.27 * t) / (237.3 + t)
    return (237.3 * gamma) / (17.27 - gamma)


def find_daily_era5_files(daily_dir: str) -> List[str]:
    patterns = [
        os.path.join(daily_dir, "ERA5_daily_Brazil_*.nc"),
        os.path.join(daily_dir, "*daily*Brazil*.nc"),
    ]
    files = []
    for pat in patterns:
        files.extend(glob.glob(pat))
    files = sorted(set(files))
    selected = []
    for f in files:
        m = re.search(r"(19|20)\d{2}", Path(f).name)
        if m:
            y = int(m.group(0))
            if START_YEAR <= y <= END_YEAR:
                selected.append(f)
    if not selected:
        raise FileNotFoundError(
            f"No preprocessed daily ERA5 files for {START_YEAR}-{END_YEAR} were found in: {daily_dir}"
        )
    return selected


def select_daily_var(ds: xr.Dataset, candidates: List[str], required: bool = True) -> xr.DataArray:
    name = find_variable(ds, candidates, required=required)
    return reduce_to_time_lat_lon(ds[name])


def process_era5_daily_year_fast(
    file_path: str,
    stations: pd.DataFrame,
    grid_index: Optional[pd.DataFrame],
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Fast station-month extraction from preprocessed daily ERA5 files.

    This avoids re-reading the full hourly ERA5 archive. It is the recommended
    mode for the 1991-2020 normal-climatology validation because Figure 1 already
    produced daily ERA5 fields on the same baseline period used for heatwave
    thresholds.
    """
    print(f"[INFO] ERA5 daily file: {Path(file_path).name}")
    ds = xr.open_dataset(file_path)
    ds = standardize_lat_lon_time(ds)
    ds = ds.sel(time=slice(f"{START_YEAR}-01-01", f"{END_YEAR}-12-31"))
    if ds.sizes.get("time", 0) == 0:
        ds.close()
        return pd.DataFrame(), grid_index

    if grid_index is None:
        grid_index = get_station_grid_indices(ds, stations)
        print(f"[INFO] ERA5 nearest grid cells prepared for {len(grid_index)} stations")

    station_dim = "station"
    iy = xr.DataArray(grid_index["iy"].to_numpy(), dims=station_dim)
    ix = xr.DataArray(grid_index["ix"].to_numpy(), dims=station_dim)

    # Daily variables from the Figure 1 preprocessing workflow.
    # TMAX/TMIN/TMEDUMID/UR/VENTIN are read directly when available.
    # TORV is reconstructed from daily mean T and RH if daily dew point is absent.
    tmean_da = select_daily_var(ds, ["Tmean", "tmean", "T2mean", "t2m_mean"], required=True)
    rh_da = select_daily_var(ds, ["RHmean", "rhmean", "RH", "relative_humidity"], required=True)

    tmax = select_daily_var(ds, ["Tmax", "tmax", "T2max", "t2m_max"], True).isel(lat=iy, lon=ix).values.astype(np.float32)
    tmin = select_daily_var(ds, ["Tmin", "tmin", "T2min", "t2m_min"], True).isel(lat=iy, lon=ix).values.astype(np.float32)
    tmean = tmean_da.isel(lat=iy, lon=ix).values.astype(np.float32)
    rh = rh_da.isel(lat=iy, lon=ix).values.astype(np.float32)

    twb_name = find_variable(ds, ["Twbmean", "twbmean", "Twb", "wetbulb"], required=False)
    if twb_name is not None:
        twb = reduce_to_time_lat_lon(ds[twb_name]).isel(lat=iy, lon=ix).values.astype(np.float32)
    else:
        twb = compute_wetbulb_stull(tmean, rh).astype(np.float32)

    ws_name = find_variable(ds, ["WS10mean", "ws10mean", "wind_speed", "WS10"], required=False)
    if ws_name is not None:
        ws = reduce_to_time_lat_lon(ds[ws_name]).isel(lat=iy, lon=ix).values.astype(np.float32)
    else:
        u_name = find_variable(ds, ["u10", "U10", "var165"], required=True)
        v_name = find_variable(ds, ["v10", "V10", "var166"], required=True)
        u = reduce_to_time_lat_lon(ds[u_name]).isel(lat=iy, lon=ix).values.astype(np.float32)
        v = reduce_to_time_lat_lon(ds[v_name]).isel(lat=iy, lon=ix).values.astype(np.float32)
        ws = np.sqrt(u**2 + v**2).astype(np.float32)

    td_name = find_variable(ds, ["Tdmean", "TDmean", "D2mean", "d2m_mean", "TORV", "dewpoint_mean"], required=False)
    if td_name is not None:
        td = maybe_kelvin_to_celsius(reduce_to_time_lat_lon(ds[td_name])).isel(lat=iy, lon=ix).values.astype(np.float32)
    else:
        td = dewpoint_from_t_rh(tmean, rh).astype(np.float32)

    time_index = pd.DatetimeIndex(pd.to_datetime(ds["time"].values))
    station_ids = grid_index["station_id"].astype(str).values

    def monthly_long(arr: np.ndarray, var: str) -> pd.DataFrame:
        wide = pd.DataFrame(arr, index=time_index, columns=station_ids)
        monthly = wide.resample("MS").mean()
        n_days = wide.resample("MS").count()
        try:
            long_val = monthly.stack(future_stack=True).rename("era5_value").reset_index()
            long_n = n_days.stack(future_stack=True).rename("n_daily_values_era5").reset_index()
        except TypeError:
            long_val = monthly.stack(dropna=False).rename("era5_value").reset_index()
            long_n = n_days.stack(dropna=False).rename("n_daily_values_era5").reset_index()
        long_val.columns = ["date", "station_id", "era5_value"]
        long_n.columns = ["date", "station_id", "n_daily_values_era5"]
        out = long_val.merge(long_n, on=["date", "station_id"], how="left")
        out["variable"] = var
        out["year"] = pd.to_datetime(out["date"]).dt.year
        out["month"] = pd.to_datetime(out["date"]).dt.month
        return out[["station_id", "variable", "year", "month", "era5_value", "n_daily_values_era5"]]

    out = pd.concat([
        monthly_long(tmax, "TMAX"),
        monthly_long(tmin, "TMIN"),
        monthly_long(td, "TORV"),
        monthly_long(rh, "UR"),
        monthly_long(ws, "VENTIN"),
        monthly_long(twb, "TMEDUMID"),
    ], ignore_index=True)

    ds.close()
    return out, grid_index


def build_era5_monthly_climatology(
    era5_glob: str,
    stations: pd.DataFrame,
    out_dir: str,
    daily_time_basis: str,
    reuse_cache: bool,
    max_years_per_run: Optional[int] = None,
    build_cache_only: bool = False,
    era5_daily_dir: Optional[str] = None,
    source: str = "auto",
) -> Tuple[pd.DataFrame, pd.DataFrame]:
    """Build ERA5 station-month climatology.

    Preferred mode is `source=daily`, using daily ERA5 files already produced by
    the Figure 1 workflow. This is much faster than processing the 30-year hourly
    archive and is scientifically aligned with the threshold baseline. Hourly mode
    remains available for exact local-day aggregation, but it is much slower.
    """
    ensure_dir(out_dir)

    if source not in ["auto", "daily", "hourly"]:
        raise ValueError("--source must be 'auto', 'daily' or 'hourly'")

    daily_files = []
    if era5_daily_dir:
        try:
            daily_files = find_daily_era5_files(era5_daily_dir)
        except Exception as exc:
            if source == "daily":
                raise
            print(f"[WARN] Daily ERA5 files not usable: {exc}")

    use_daily = source == "daily" or (source == "auto" and len(daily_files) > 0)

    if use_daily:
        files = daily_files
        # Preprocessed daily fields retain the calendar definition used when
        # they were generated. A local-day shift cannot be reconstructed from
        # daily files alone.
        if daily_time_basis == "local_by_uf":
            print(
                "[INFO] Daily ERA5 mode uses the calendar definition already "
                "stored in the daily files; local-day shifting is applied only "
                "in hourly mode."
            )
        tag = "DailyFast"
        processor = lambda f, gi: process_era5_daily_year_fast(f, stations, gi)
    else:
        if not era5_glob:
            raise ValueError(
                "Hourly ERA5 input is required because daily files were not "
                "selected or available."
            )
        files = resolve_era5_files(era5_glob)
        tag = "UTCmonth" if daily_time_basis == "utc" else "LocalUFmonth"
        processor = lambda f, gi: process_era5_year(
            f, stations, gi, daily_time_basis
        )

    cache_grid = os.path.join(out_dir, f"CACHE_ERA5_normals_station_grid_index_{tag}.csv")
    cache_all = os.path.join(out_dir, f"CACHE_ERA5_station_monthly_climatology_1991_2020_{tag}.csv")

    if reuse_cache and os.path.exists(cache_all) and os.path.exists(cache_grid) and not build_cache_only:
        print(f"[INFO] Reusing combined ERA5 monthly climatology cache: {Path(cache_all).name}")
        clim = pd.read_csv(cache_all)
        grid_index = pd.read_csv(cache_grid)
        clim["station_id"] = clim["station_id"].astype(str)
        grid_index["station_id"] = grid_index["station_id"].astype(str)
        return clim, grid_index

    grid_index = None
    if reuse_cache and os.path.exists(cache_grid):
        grid_index = pd.read_csv(cache_grid)
        grid_index["station_id"] = grid_index["station_id"].astype(str)
        print(f"[INFO] Reusing ERA5 station grid-index cache: {Path(cache_grid).name}")

    all_yearly = []
    processed_this_run = 0

    for i, f in enumerate(files, 1):
        year_label = year_from_path(f)
        cache_year = os.path.join(out_dir, f"CACHE_ERA5_station_monthly_{year_label}_{tag}.csv")
        tmp_year = cache_year + ".tmp"

        if reuse_cache and os.path.exists(cache_year):
            print(f"[SKIP] Reusing cached ERA5 station-monthly file {i}/{len(files)}: {Path(cache_year).name}")
            dfy = pd.read_csv(cache_year)
            dfy["station_id"] = dfy["station_id"].astype(str)
            all_yearly.append(dfy)
            continue

        if max_years_per_run is not None and processed_this_run >= max_years_per_run:
            print(f"[STOP] Reached --max_years_per_run={max_years_per_run}. Re-run to continue.")
            continue

        print(f"[INFO] Processing ERA5 file {i}/{len(files)}")
        dfy, grid_index = processor(f, grid_index)
        if grid_index is not None:
            grid_index.to_csv(cache_grid, index=False)
        if not dfy.empty:
            dfy.to_csv(tmp_year, index=False)
            os.replace(tmp_year, cache_year)
            print(f"[OK] Cached ERA5 station-monthly year: {cache_year}")
            all_yearly.append(dfy)
        processed_this_run += 1

    if build_cache_only:
        print("[DONE] Cache-building mode requested. Metrics/figures were not generated.")
        return pd.DataFrame(), grid_index

    if not all_yearly:
        raise RuntimeError("No ERA5 station-monthly data available. Build or reuse yearly caches first.")

    monthly = pd.concat(all_yearly, ignore_index=True)
    monthly = monthly[(monthly["year"] >= START_YEAR) & (monthly["year"] <= END_YEAR)].copy()
    monthly["station_id"] = monthly["station_id"].astype(str)
    monthly["era5_value"] = pd.to_numeric(monthly["era5_value"], errors="coerce")

    clim = (
        monthly.dropna(subset=["era5_value"])
        .groupby(["station_id", "variable", "month"], as_index=False)
        .agg(
            era5_climatology=("era5_value", "mean"),
            n_year_months_era5=("era5_value", "count"),
            n_daily_values_era5=("n_daily_values_era5", "sum"),
        )
    )
    clim.to_csv(cache_all, index=False)
    print(f"[OK] Cached ERA5 monthly climatology: {cache_all}")
    return clim, grid_index


