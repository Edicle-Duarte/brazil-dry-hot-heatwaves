def read_states_shapefile(path: str) -> gpd.GeoDataFrame:
    if not os.path.exists(path):
        raise FileNotFoundError(f"State shapefile not found: {path}")
    gdf = gpd.read_file(path)
    gdf = gdf.to_crs("EPSG:4326") if gdf.crs is not None else gdf.set_crs("EPSG:4326")

    state_name_to_uf = {
        "ACRE": "AC", "ALAGOAS": "AL", "AMAPA": "AP", "AMAPÁ": "AP", "AMAZONAS": "AM",
        "BAHIA": "BA", "CEARA": "CE", "CEARÁ": "CE", "DISTRITO FEDERAL": "DF",
        "ESPIRITO SANTO": "ES", "ESPÍRITO SANTO": "ES", "GOIAS": "GO", "GOIÁS": "GO",
        "MARANHAO": "MA", "MARANHÃO": "MA", "MATO GROSSO": "MT", "MATO GROSSO DO SUL": "MS",
        "MINAS GERAIS": "MG", "PARA": "PA", "PARÁ": "PA", "PARAIBA": "PB", "PARAÍBA": "PB",
        "PARANA": "PR", "PARANÁ": "PR", "PERNAMBUCO": "PE", "PIAUI": "PI", "PIAUÍ": "PI",
        "RIO DE JANEIRO": "RJ", "RIO GRANDE DO NORTE": "RN", "RIO GRANDE DO SUL": "RS",
        "RONDONIA": "RO", "RONDÔNIA": "RO", "RORAIMA": "RR", "SANTA CATARINA": "SC",
        "SAO PAULO": "SP", "SÃO PAULO": "SP", "SERGIPE": "SE", "TOCANTINS": "TO",
    }
    state_name_to_uf_norm = {normalize_name(k): v for k, v in state_name_to_uf.items()}

    uf_col = None
    for c in gdf.columns:
        cl = normalize_name(c)
        if cl in ["uf", "sigla", "sigla_uf", "uf_05", "sigla_uf_05"]:
            vals = gdf[c].astype(str).str.upper().str.extract(r"([A-Z]{2})")[0]
            if vals.isin(list(UF_TO_REGION.keys())).sum() >= 10:
                gdf["uf"] = vals
                uf_col = c
                break
    if uf_col is None:
        for c in gdf.columns:
            if c == "geometry":
                continue
            vals = gdf[c].astype(str).map(normalize_name)
            if vals.isin(state_name_to_uf_norm.keys()).sum() >= 10:
                gdf["uf"] = vals.map(state_name_to_uf_norm)
                uf_col = c
                break
    if uf_col is None:
        raise ValueError(f"Could not identify UF or state-name column in {path}. Columns: {list(gdf.columns)}")
    gdf = gdf[gdf["uf"].isin(UF_TO_REGION)].copy()
    gdf = gdf[["uf", "geometry"]].dissolve(by="uf", as_index=False)
    return gdf


def point_size_from_n(n):
    """Return conservative marker sizes for station maps.

    Marker size represents station sample size while limiting visual overlap.
    """
    n = np.asarray(n, float)
    if len(n) == 0 or not np.isfinite(n).any():
        return np.full_like(n, 18.0, dtype=float)
    lo, hi = np.nanpercentile(n, [5, 95])
    if hi <= lo:
        return np.full_like(n, 20.0, dtype=float)
    return 10.0 + 28.0 * np.clip((n - lo) / (hi - lo), 0, 1)


def format_map_axis(ax, states, row_idx=None, col_idx=None):
    """Format Brazil station-map panels with compact, non-overlapping labels."""
    states.boundary.plot(ax=ax, color="0.35", linewidth=0.35, zorder=2)
