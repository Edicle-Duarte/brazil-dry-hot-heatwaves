def find_station_file(normal_dir: str) -> str:
    candidates = []
    candidates.extend(glob.glob(os.path.join(normal_dir, "Normal-Climatologica-ESTA*.xlsx")))
    candidates.extend(glob.glob(os.path.join(normal_dir, "*ESTA*.xlsx")))
    if not candidates:
        raise FileNotFoundError(
            "Could not find station metadata file. Expected something like "
            "Normal-Climatologica-ESTAÇÕES.xlsx in --normal_dir."
        )
    return sorted(candidates)[0]


def read_station_metadata(normal_dir: str) -> pd.DataFrame:
    path = find_station_file(normal_dir)
    header = find_header_row(path, ["Código", "Latitude", "Longitude"])
    df = pd.read_excel(path, header=header)
    df.columns = [str(c).strip() for c in df.columns]

    code_col = find_col(df.columns, ["Código", "Codigo", "Cod"], True)
    name_col = find_col(df.columns, ["Nome da Estação", "Nome da Estacao", "Estação", "Estacao"], False)
    uf_col = find_col(df.columns, ["UF"], True)
    lat_col = find_col(df.columns, ["Latitude"], True)
    lon_col = find_col(df.columns, ["Longitude"], True)
    alt_col = find_col(df.columns, ["Altitude"], False)
    status_col = find_col(df.columns, ["Situação", "Situacao"], False)

    out = pd.DataFrame({
        "station_id": df[code_col].map(normalize_station_code),
        "station_name": df[name_col].astype(str).str.strip() if name_col else "",
        "uf": df[uf_col].astype(str).str.upper().str.extract(r"([A-Z]{2})")[0],
        "lat": df[lat_col].map(clean_numeric),
        "lon": df[lon_col].map(clean_numeric),
        "altitude_m": df[alt_col].map(clean_numeric) if alt_col else np.nan,
        "status": df[status_col].astype(str).str.strip() if status_col else "",
    })
    out = out.dropna(subset=["station_id", "uf", "lat", "lon"])
    out = out[out["uf"].isin(UF_TO_REGION)].copy()
    out["region"] = out["uf"].map(UF_TO_REGION)
    out = out.drop_duplicates(subset=["station_id", "uf"], keep="first").reset_index(drop=True)
    print(f"[INFO] Station metadata: {len(out)} stations from {Path(path).name}")
    return out


def read_normal_variable_file(path: str, variable: str) -> pd.DataFrame:
    header = find_header_row(path, ["Código", "Janeiro", "Dezembro"])
    df = pd.read_excel(path, header=header)
    df.columns = [str(c).strip() for c in df.columns]

    code_col = find_col(df.columns, ["Código", "Codigo", "Cod"], True)
    name_col = find_col(df.columns, ["Nome da Estação", "Nome da Estacao", "Estação", "Estacao"], False)
    uf_col = find_col(df.columns, ["UF"], True)

    month_cols = []
    for m in MONTHS_PT:
        col = find_col(df.columns, [m], required=False)
        if col is not None:
            month_cols.append((m, col))
    if len(month_cols) < 6:
        raise ValueError(f"Too few month columns detected in {path}: {month_cols}")

    rows = []
    for _, r in df.iterrows():
        sid = normalize_station_code(r[code_col])
        if sid is None:
            continue
        uf = str(r[uf_col]).upper().strip()
        uf_match = re.search(r"([A-Z]{2})", uf)
        uf = uf_match.group(1) if uf_match else uf
        for m_name, col in month_cols:
            val = clean_numeric(r[col])
            if np.isfinite(val):
                rows.append({
                    "station_id": sid,
                    "station_name_inmet": str(r[name_col]).strip() if name_col else "",
                    "uf": uf,
                    "variable": variable,
                    "month": MONTH_TO_NUM[m_name],
                    "month_name": m_name,
                    "inmet_normal": float(val),
                })
    out = pd.DataFrame(rows)
    print(f"[INFO] INMET normals {variable}: {len(out)} station-month rows from {Path(path).name}")
    return out


def read_all_inmet_normals(normal_dir: str, stations: pd.DataFrame) -> pd.DataFrame:
    frames = []
    for var in VAR_ORDER:
        path = os.path.join(normal_dir, VARIABLES[var]["file"])
        if not os.path.exists(path):
            raise FileNotFoundError(f"Missing required normal file for {var}: {path}")
        frames.append(read_normal_variable_file(path, var))

    normals = pd.concat(frames, ignore_index=True)
    normals = normals.merge(
        stations[["station_id", "uf", "station_name", "lat", "lon", "altitude_m", "status", "region"]],
        on=["station_id", "uf"],
        how="inner",
    )
    normals = normals.dropna(subset=["lat", "lon", "inmet_normal"])
    print(f"[INFO] INMET normals matched to station coordinates: {len(normals)} rows")
    return normals


