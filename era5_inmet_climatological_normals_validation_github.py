def main():
    ap = argparse.ArgumentParser(
        description=(
            "Validate ERA5 monthly climatology against INMET 1991–2020 "
            "climatological normals."
        )
    )
    ap.add_argument(
        "--normal-dir", "--normal_dir",
        dest="normal_dir",
        required=True,
        help="Directory containing INMET climatological-normal Excel files.",
    )
    ap.add_argument(
        "--era5-hourly-glob", "--era5_hourly_glob",
        dest="era5_hourly_glob",
        default=None,
        help=(
            "Glob pattern for hourly ERA5 NetCDF files. Required for hourly "
            "mode and as the fallback source in auto mode."
        ),
    )
    ap.add_argument(
        "--era5-daily-dir", "--era5_daily_dir",
        dest="era5_daily_dir",
        default=None,
        help=(
            "Directory containing preprocessed daily ERA5 files generated by "
            "the Figure 01 workflow."
        ),
    )
    ap.add_argument(
        "--source",
        choices=["auto", "daily", "hourly"],
        default="auto",
        help=(
            "ERA5 source mode. 'auto' uses daily files when available and "
            "otherwise falls back to hourly files."
        ),
    )
    ap.add_argument(
        "--states-shapefile", "--shp_uf",
        dest="shp_uf",
        required=True,
        help="Brazilian state shapefile.",
    )
    ap.add_argument(
        "--output-dir", "--out_dir",
        dest="out_dir",
        required=True,
        help="Output directory.",
    )
    ap.add_argument(
        "--daily-time-basis", "--daily_time_basis",
        dest="daily_time_basis",
        choices=["utc", "local_by_uf"],
        default="local_by_uf",
        help=(
            "Time basis used before daily aggregation in hourly mode. "
            "Default: local_by_uf."
        ),
    )
    ap.add_argument(
        "--reuse-era5-cache", "--reuse_era5_cache",
        dest="reuse_era5_cache",
        action="store_true",
        help="Reuse yearly and combined ERA5 station-month caches.",
    )
    ap.add_argument(
        "--max-years-per-run", "--max_years_per_run",
        dest="max_years_per_run",
        type=int,
        default=None,
        help="Process at most this many uncached ERA5 years in one run.",
    )
    ap.add_argument(
        "--build-era5-cache-only", "--build_era5_cache_only",
        dest="build_era5_cache_only",
        action="store_true",
        help="Build/reuse ERA5 caches without computing metrics or plotting.",
    )
    ap.add_argument(
        "--min-months", "--min_months",
        dest="min_months",
        type=int,
        default=8,
        help="Minimum paired months required for station-level metrics.",
    )
    args = ap.parse_args()

    if args.source == "daily" and not args.era5_daily_dir:
        ap.error("--era5-daily-dir is required when --source daily is used.")
    if args.source == "hourly" and not args.era5_hourly_glob:
        ap.error("--era5-hourly-glob is required when --source hourly is used.")
    if args.source == "auto" and not args.era5_daily_dir and not args.era5_hourly_glob:
        ap.error(
            "--source auto requires --era5-daily-dir and/or --era5-hourly-glob."
        )

    ensure_dir(args.out_dir)
    print("[START] ERA5 vs INMET climatological-normal validation, 1991-2020")
    print(f"[INFO] INMET normal directory: {args.normal_dir}")
    print(f"[INFO] ERA5 hourly glob: {args.era5_hourly_glob or 'not supplied'}")
    print(f"[INFO] ERA5 daily directory: {args.era5_daily_dir or 'not supplied'}")
    print(f"[INFO] ERA5 source mode: {args.source}")
    print(f"[INFO] Time basis for ERA5 aggregation: {args.daily_time_basis}")

    stations = read_station_metadata(args.normal_dir)
    inmet_normals = read_all_inmet_normals(args.normal_dir, stations)

    era5_clim, grid_index = build_era5_monthly_climatology(
        era5_glob=args.era5_hourly_glob,
        stations=stations,
        out_dir=args.out_dir,
        daily_time_basis=args.daily_time_basis,
        reuse_cache=args.reuse_era5_cache,
        max_years_per_run=args.max_years_per_run,
        build_cache_only=args.build_era5_cache_only,
        era5_daily_dir=args.era5_daily_dir,
        source=args.source,
    )

    if args.build_era5_cache_only:
        return

    paired = inmet_normals.merge(
        era5_clim,
        on=["station_id", "variable", "month"],
        how="inner",
    )
    paired = paired.dropna(subset=["inmet_normal", "era5_climatology", "lat", "lon"])
    paired["difference_era5_minus_inmet"] = paired["era5_climatology"] - paired["inmet_normal"]
    print(f"[INFO] Paired INMET-ERA5 station-month rows: {len(paired)}")

    station_metrics = station_metric_table(paired, min_months=args.min_months)
    print(f"[INFO] Station-level metrics rows: {len(station_metrics)}")
    taylor_df = compute_taylor_metrics(paired)
    states = read_states_shapefile(args.shp_uf)

    metadata = {
        "script": Path(__file__).name,
        "period": f"{START_YEAR}-{END_YEAR}",
        "normal_dir": args.normal_dir,
        "era5_hourly_glob": args.era5_hourly_glob,
        "era5_daily_dir": args.era5_daily_dir,
        "era5_source": args.source,
        "states_shapefile": args.shp_uf,
        "daily_time_basis": args.daily_time_basis,
        "daily_mode_note": (
            "Preprocessed daily files retain their existing calendar-day "
            "definition; state-level local-day shifting is applied only in "
            "hourly mode."
        ),
        "variables": VAR_ORDER,
        "units": {v: VARIABLES[v]["unit"] for v in VAR_ORDER},
        "era5_aggregation": {
            "TMAX": "daily maximum 2-m temperature, then monthly climatological mean",
            "TMIN": "daily minimum 2-m temperature, then monthly climatological mean",
            "TORV": "daily mean 2-m dew-point temperature, then monthly climatological mean",
            "UR": "daily mean relative humidity calculated from 2-m temperature and dew point, then monthly climatological mean",
            "VENTIN": "daily mean 10-m wind speed from u10/v10, then monthly climatological mean",
            "TMEDUMID": "daily mean wet-bulb temperature from Stull approximation, then monthly climatological mean",
        },
        "metrics": ["Pearson r", "RMSE", "Bias = ERA5 - INMET", "MAE", "Taylor metrics"],
    }

    save_outputs(paired, station_metrics, taylor_df, stations, grid_index, args.out_dir, metadata)
    plot_validation_figure(station_metrics, taylor_df, states, args.out_dir)
    print("[DONE] ERA5 climatological-normal validation completed.")


if __name__ == "__main__":
    warnings.filterwarnings("ignore", category=RuntimeWarning)
    main()

