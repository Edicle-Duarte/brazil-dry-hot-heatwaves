"""
ERA5 validation against INMET 1991–2020 climatological normals.

Purpose
-------
Compare ERA5 monthly climatologies with INMET 1991–2020 climatological normals
at station locations. This evaluation focuses on the baseline climatology used
for heatwave-threshold analyses; it does not evaluate individual heatwave
events or daily weather variability.

INMET variables
---------------
The directory supplied through ``--normal-dir`` must contain:

  Normal-Climatologica-ESTAÇÕES.xlsx
  Normal-Climatologica-TMAX.xlsx
  Normal-Climatologica-TMIN.xlsx
  Normal-Climatologica-TORV.xlsx
  Normal-Climatologica-UR.xlsx
  Normal-Climatologica-VENTIN.xlsx
  Normal-Climatologica-TMEDUMID.xlsx

ERA5 processing
---------------
Two input modes are supported:

``daily``
    Uses daily ERA5 files previously generated by the Figure 01 workflow.
    This is the recommended mode for climatological-normal evaluation.

``hourly``
    Uses hourly ERA5 single-level files and permits daily aggregation in UTC
    or by fixed state-level UTC offsets.

``auto``
    Uses daily files when supplied and available; otherwise uses hourly files.

At each INMET station, the nearest ERA5 grid cell is used. TMAX and TMIN are
derived from daily extrema. Dew-point temperature, relative humidity, 10-m wind
speed, and wet-bulb temperature are evaluated as monthly climatological means.

Outputs
-------
Station-month paired values, station-level metrics, regional/national Taylor
metrics, station metadata, nearest-grid metadata, an Excel workbook, software
metadata, and a publication-ready validation figure.

Example: daily mode
-------------------
python era5_inmet_climatological_normals_validation.py \
    --normal-dir /path/to/inmet_normals_1991_2020 \
    --era5-daily-dir /path/to/figure_01_outputs/cache/era5_daily \
    --source daily \
    --states-shapefile /path/to/brazil_states.shp \
    --output-dir ./outputs/era5_inmet_climatology \
    --reuse-era5-cache

Example: hourly mode
--------------------
python era5_inmet_climatological_normals_validation.py \
    --normal-dir /path/to/inmet_normals_1991_2020 \
    --era5-hourly-glob "/path/to/era5_hourly_*.nc" \
    --source hourly \
    --states-shapefile /path/to/brazil_states.shp \
    --output-dir ./outputs/era5_inmet_climatology \
    --daily-time-basis local_by_uf
"""

