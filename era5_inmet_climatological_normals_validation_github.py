def ensure_dir(path: str):
    os.makedirs(path, exist_ok=True)


def normalize_name(s: str) -> str:
    s = str(s).strip().lower()
    repl = {
        "á": "a", "à": "a", "â": "a", "ã": "a", "ä": "a",
        "é": "e", "ê": "e", "í": "i", "ó": "o", "ô": "o", "õ": "o",
        "ú": "u", "ç": "c", "º": "", "ª": "",
    }
    for a, b in repl.items():
        s = s.replace(a, b)
    s = re.sub(r"[^a-z0-9]+", "_", s)
    return re.sub(r"_+", "_", s).strip("_")


def normalize_station_code(x) -> Optional[str]:
    if pd.isna(x):
        return None
    s = str(x).strip()
    if not s:
        return None
    # Excel may read code as 83249.0.
    try:
        f = float(s.replace(",", "."))
        if np.isfinite(f) and abs(f - round(f)) < 1e-6:
            return str(int(round(f)))
    except Exception:
        pass
    m = re.search(r"\d+", s)
    return m.group(0) if m else None


def clean_numeric(x):
    if pd.isna(x):
        return np.nan
    if isinstance(x, (int, float, np.integer, np.floating)):
        return float(x)
    s = str(x).strip()
    if s in ["", "-", "–", "--", "nan", "NaN"]:
        return np.nan
    s = s.replace(",", ".")
    s = re.sub(r"[^0-9eE+\-.]", "", s)
    try:
        return float(s)
    except Exception:
        return np.nan


def find_header_row(path: str, required_terms: List[str], max_rows: int = 15) -> int:
    raw = pd.read_excel(path, header=None, nrows=max_rows)
    req = [normalize_name(t) for t in required_terms]
    for i in range(len(raw)):
        vals = [normalize_name(v) for v in raw.iloc[i].tolist()]
        row = " ".join(vals)
        if all(any(r in v for v in vals) or r in row for r in req):
            return i
    return 2


def find_col(columns, candidates: List[str], required: bool = True) -> Optional[str]:
    norm = {normalize_name(c): c for c in columns}
    cand = [normalize_name(c) for c in candidates]
    for cc in cand:
        if cc in norm:
            return norm[cc]
    for c in columns:
        nc = normalize_name(c)
        for cc in cand:
            if cc and (cc in nc or nc in cc):
                return c
    if required:
        raise ValueError(f"Could not find column among {candidates}. Available: {list(columns)}")
    return None


