def station_metric_table(paired: pd.DataFrame, min_months: int) -> pd.DataFrame:
    rows = []
    for (sid, var), g in paired.groupby(["station_id", "variable"]):
        obs = pd.to_numeric(g["inmet_normal"], errors="coerce").to_numpy(float)
        mod = pd.to_numeric(g["era5_climatology"], errors="coerce").to_numpy(float)
        ok = np.isfinite(obs) & np.isfinite(mod)
        obs = obs[ok]
        mod = mod[ok]
        if len(obs) < min_months:
            continue
        if np.nanstd(obs) > 0 and np.nanstd(mod) > 0 and len(obs) >= 2:
            r = float(np.corrcoef(obs, mod)[0, 1])
        else:
            r = np.nan
        diff = mod - obs
        rows.append({
            "station_id": sid,
            "variable": var,
            "pearson_r": r,
            "rmse": float(np.sqrt(np.nanmean(diff ** 2))),
            "bias_era5_minus_inmet": float(np.nanmean(diff)),
            "mae": float(np.nanmean(np.abs(diff))),
            "n_months": int(len(obs)),
            "obs_mean": float(np.nanmean(obs)),
            "era5_mean": float(np.nanmean(mod)),
            "obs_std": float(np.nanstd(obs, ddof=1)) if len(obs) > 1 else np.nan,
            "era5_std": float(np.nanstd(mod, ddof=1)) if len(mod) > 1 else np.nan,
        })
    metrics = pd.DataFrame(rows)
    meta_cols = ["station_id", "uf", "station_name", "lat", "lon", "altitude_m", "status", "region"]
    meta = paired[meta_cols].drop_duplicates(subset=["station_id"])
    metrics = metrics.merge(meta, on="station_id", how="left")
    return metrics


def paired_arrays_for_group(paired: pd.DataFrame, variable: str, region: str) -> Tuple[np.ndarray, np.ndarray]:
    d = paired[paired["variable"] == variable].copy()
    if region != "Brazil":
        d = d[d["region"] == region].copy()
    obs = pd.to_numeric(d["inmet_normal"], errors="coerce").to_numpy(float)
    mod = pd.to_numeric(d["era5_climatology"], errors="coerce").to_numpy(float)
    ok = np.isfinite(obs) & np.isfinite(mod)
    return obs[ok], mod[ok]


def compute_taylor_metrics(paired: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for var in VAR_ORDER:
        for region in REGION_ORDER:
            obs, mod = paired_arrays_for_group(paired, var, region)
            if len(obs) < 8 or np.nanstd(obs, ddof=1) == 0 or np.nanstd(mod, ddof=1) == 0:
                corr = std_norm = rmse_norm = crmse_norm = np.nan
            else:
                corr = float(np.corrcoef(obs, mod)[0, 1])
                std_norm = float(np.nanstd(mod, ddof=1) / np.nanstd(obs, ddof=1))
                rmse_norm = float(np.sqrt(np.nanmean((mod - obs) ** 2)) / np.nanstd(obs, ddof=1))
                obs_anom = obs - np.nanmean(obs)
                mod_anom = mod - np.nanmean(mod)
                crmse_norm = float(np.sqrt(np.nanmean((mod_anom - obs_anom) ** 2)) / np.nanstd(obs, ddof=1))
            rows.append({
                "variable": var,
                "region": region,
                "n_pairs": int(len(obs)),
                "corr": corr,
                "std_norm": std_norm,
                "rmse_norm": rmse_norm,
                "crmse_norm": crmse_norm,
            })
    return pd.DataFrame(rows)


