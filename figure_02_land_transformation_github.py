def add_colorbar(fig, ax, cmap, norm, label, ticks=None, ticklabels=None):
    sm = plt.cm.ScalarMappable(cmap=cmap, norm=norm)
    sm.set_array([])

    divider = make_axes_locatable(ax)
    cax = divider.append_axes("right", size="3.0%", pad=0.03)
    cb = fig.colorbar(sm, cax=cax, ticks=ticks)
    cb.set_label(label, fontsize=11)
    cb.ax.tick_params(labelsize=11)
    if ticklabels is not None:
        cb.ax.set_yticklabels(ticklabels)


def add_stippling(ax, gdf):
    stip = gdf[gdf["dry_shift_stipple"] == True].copy()
    if stip.empty:
        return
    pts = stip.geometry.representative_point()
    ax.scatter(pts.x, pts.y, s=1.2, c="black", alpha=0.55, linewidths=0, zorder=5)


def plot_map(ax, gdf, column, title, cmap, norm, cbar_label, stipple=False,
             ticks=None, ticklabels=None):
    vals = pd.to_numeric(gdf[column], errors="coerce")
    valid = gdf[np.isfinite(vals)].copy()

    gdf.plot(ax=ax, color="0.94", edgecolor="none", linewidth=0, zorder=1)
    valid.plot(
        ax=ax,
        column=column,
        cmap=cmap,
        norm=norm,
        linewidth=0.03,
        edgecolor="0.75",
        zorder=2,
    )
    gdf.boundary.plot(ax=ax, color="0.55", linewidth=0.025, zorder=3)

    if stipple:
        add_stippling(ax, gdf)

    ax.set_xlim(LON_MIN, LON_MAX)
    ax.set_ylim(LAT_MIN, LAT_MAX)
    ax.set_axis_off()
    ax.set_title(title, fontsize=13, fontweight="bold", pad=5)

    add_colorbar(ax.figure, ax, cmap, norm, cbar_label, ticks=ticks, ticklabels=ticklabels)


