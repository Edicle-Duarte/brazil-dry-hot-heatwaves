def read_mapbiomas():
    print(f"[INFO] Reading MapBiomas coverage: {COVERAGE_XLSX}")
    df = pd.read_excel(COVERAGE_XLSX, sheet_name="COVERAGE_10.1")

    required = [
        "country", "biome", "state", "state_acronym", "municipality",
        "class_level_1", "class_level_2", YEAR0, YEAR1
    ]
    missing = [c for c in required if c not in df.columns]
    if missing:
        raise ValueError(f"Missing columns in MapBiomas file: {missing}")

    for y in [YEAR0, YEAR1]:
        df[y] = pd.to_numeric(df[y], errors="coerce")

    df["municipality_norm"] = df["municipality"].map(normalize_text)
    df["state_acronym_norm"] = df["state_acronym"].map(normalize_text)
    df["biome_clean"] = df["biome"].map(normalize_biome)
    df["class1_norm"] = df["class_level_1"].map(normalize_class)
    df["class2_norm"] = df["class_level_2"].map(normalize_class)

    return df


def build_landcover_municipality_biome(df):
    print(f"[INFO] Building land-cover metrics for {YEAR0}–{YEAR1}.")

    id_cols = [
        "country", "biome", "biome_clean", "state", "state_acronym",
        "municipality", "municipality_norm", "state_acronym_norm"
    ]

    total = (
        df.groupby(id_cols, dropna=False)[[YEAR0, YEAR1]]
        .sum()
        .rename(columns={YEAR0: "total_area_1990_ha", YEAR1: "total_area_2024_ha"})
        .reset_index()
    )

    def agg(mask, prefix):
        return (
            df.loc[mask]
            .groupby(id_cols, dropna=False)[[YEAR0, YEAR1]]
            .sum()
            .rename(columns={YEAR0: f"{prefix}_1990_ha", YEAR1: f"{prefix}_2024_ha"})
            .reset_index()
        )

    out = total.copy()
    groups = {
        "native": df["class1_norm"].isin(NATIVE_LEVEL1),
        "agro": df["class1_norm"].isin(AGRO_LEVEL1),
        "urban": df["class2_norm"].isin(URBAN_LEVEL2),
    }

    for prefix, mask in groups.items():
        out = out.merge(agg(mask, prefix), on=id_cols, how="left")

    area_cols = [c for c in out.columns if c.endswith("_ha")]
    out[area_cols] = out[area_cols].fillna(0.0)

    before = len(out)
    out = out[out["total_area_2024_ha"] >= MIN_AREA_HA].copy()
    print(f"[QC] Removed {before - len(out)} municipality-biome rows with area < {MIN_AREA_HA:.0f} ha.")

    den0 = out["total_area_1990_ha"].values
    den1 = out["total_area_2024_ha"].values

    for group in ["native", "agro", "urban"]:
        out[f"{group}_frac_1990"] = safe_div(out[f"{group}_1990_ha"].values, den0)
        out[f"{group}_frac_2024"] = safe_div(out[f"{group}_2024_ha"].values, den1)
        out[f"{group}_pct_1990"] = 100.0 * out[f"{group}_frac_1990"]
        out[f"{group}_pct_2024"] = 100.0 * out[f"{group}_frac_2024"]

    out["veg_loss_pct_points"] = out["native_pct_1990"] - out["native_pct_2024"]
    out["agri_gain_pct_points"] = out["agro_pct_2024"] - out["agro_pct_1990"]
    out["urban_gain_pct_points"] = out["urban_pct_2024"] - out["urban_pct_1990"]

    return out


