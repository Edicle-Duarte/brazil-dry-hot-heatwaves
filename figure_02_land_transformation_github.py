def load_municipality_geometry():
    shp = find_municipality_shapefile()
    print(f"[INFO] Reading municipality shapefile: {shp}")

    gdf = gpd.read_file(shp).to_crs(epsg=4326)

    name_col = detect_column(gdf.columns, [
        "NM_MUN", "NM_MUNICIP", "NM_MUNICIPIO", "NOME", "MUNICIPIO", "municipality", "name"
    ])
    state_col = detect_column(gdf.columns, [
        "SIGLA_UF", "UF", "state_acronym", "SIGLA"
    ])

    if name_col is None or state_col is None:
        raise ValueError(f"Could not detect municipality/state columns. Columns: {list(gdf.columns)}")

    gdf["municipality_norm"] = gdf[name_col].map(normalize_text)
    gdf["state_acronym_norm"] = gdf[state_col].map(normalize_text)

    pts = gdf.geometry.representative_point()
    gdf["rep_lon"] = pts.x
    gdf["rep_lat"] = pts.y

    return gdf


def aggregate_to_municipality(df):
    print("[INFO] Aggregating municipality-biome rows to municipality level.")

    rows = []
    group_cols = ["municipality_norm", "state_acronym_norm"]

    vars_to_weight = [
        "veg_loss_pct_points",
        "agri_gain_pct_points",
        "urban_gain_pct_points",
        "native_pct_1990",
        "native_pct_2024",
        "agro_pct_1990",
        "agro_pct_2024",
        "urban_pct_1990",
        "urban_pct_2024",
    ]

    for keys, g in df.groupby(group_cols, dropna=False):
        municipality_norm, state_acronym_norm = keys
        total_area = g["total_area_2024_ha"].sum()

        row = {
            "municipality_norm": municipality_norm,
            "state_acronym_norm": state_acronym_norm,
            "municipality": g["municipality"].iloc[0],
            "state_acronym": g["state_acronym"].iloc[0],
            "total_area_2024_ha": total_area,
            "n_biome_rows": len(g),
        }

        gi = g.loc[g["total_area_2024_ha"].idxmax()]
        row["dominant_biome"] = gi["biome_clean"]
        row["dominant_biome_area_fraction"] = (
            gi["total_area_2024_ha"] / total_area if total_area > 0 else np.nan
        )

        for c in vars_to_weight:
            row[c] = weighted_mean(g, c)

        rows.append(row)

    out = pd.DataFrame(rows)

    # Cumulative landscape-state metrics used in the revised main Figure 2.
    # These variables capture the 2024 transformed state of each municipality,
    # which the controlled diagnostics showed to be more robust than recent
    # agricultural expansion alone.
    out["transformed_non_native_pct_2024"] = 100.0 - pd.to_numeric(out["native_pct_2024"], errors="coerce")
    out["transformed_non_native_pct_1990"] = 100.0 - pd.to_numeric(out["native_pct_1990"], errors="coerce")

    out = add_focus_regions(out)
    return out


def add_focus_regions(df):
    df = df.copy()

    state = df["state_acronym_norm"].astype(str).str.upper()
    dom = df["dominant_biome"].astype(str)

    se = state.isin(SOUTHEAST_STATES)
    urban_gain = pd.to_numeric(df["urban_gain_pct_points"], errors="coerce")
    urban_pct_2024 = pd.to_numeric(df.get("urban_pct_2024", np.nan), errors="coerce")

    se_gain_thr = np.nanpercentile(urban_gain[se], 75) if np.isfinite(urban_gain[se]).any() else np.nan
    se_urban_thr = np.nanpercentile(urban_pct_2024[se], 75) if np.isfinite(urban_pct_2024[se]).any() else np.nan

    is_southeast_urban = se & ((urban_gain >= se_gain_thr) | (urban_pct_2024 >= se_urban_thr))
    is_matopiba = state.isin(MATOPIBA_STATES) & dom.isin(["Cerrado", "Caatinga"])
    is_semiarid = state.isin(SEMIARID_STATES) & dom.eq("Caatinga")

    region = dom.copy().astype(object)
    region[is_semiarid.values] = "Semiárido"
    region[is_matopiba.values] = "MATOPIBA"
    region[is_southeast_urban.values] = "Sudeste urbano"

    region = np.where(np.isin(region, REGION_ORDER), region, "Other")
    df["focus_region"] = region

    return df


def build_era5_point_gdf(ds):
    lon = ds["lon"].values
    lat = ds["lat"].values

    if np.nanmax(lon) > 180:
        lon = ((lon + 180) % 360) - 180

    lon2d, lat2d = np.meshgrid(lon, lat)

    data = {
        "era5_lat": lat2d.ravel(),
        "era5_lon": lon2d.ravel(),
    }

    trend_vars = [v for v in ds.data_vars if v.endswith("_trend_decade") or v.endswith("_pvalue")]

    for v in trend_vars:
        arr = ds[v].values
        data[v] = arr.ravel()

    pts = gpd.GeoDataFrame(
        data,
        geometry=gpd.points_from_xy(data["era5_lon"], data["era5_lat"]),
        crs="EPSG:4326"
    )

    pts = pts[
        (pts["era5_lon"] >= LON_MIN - 1)
        & (pts["era5_lon"] <= LON_MAX + 1)
        & (pts["era5_lat"] >= LAT_MIN - 1)
        & (pts["era5_lat"] <= LAT_MAX + 1)
    ].copy()

    return pts, trend_vars


def aggregate_era5_to_municipalities_zonal(gdf_mun, ds):
    """Aggregate continuous ERA5 trends with cos(latitude) weights.

    P-values are not averaged. Municipality statistical support is represented
    by the cos(latitude)-weighted fraction of contributing grid cells with a
    positive DHW Tmax-only trend and p <= 0.05.
    """
    print("[INFO] Integrating ERA5 trends by municipality zonal aggregation.")
    pts, vars_all = build_era5_point_gdf(ds)
    pts["grid_weight"] = np.cos(np.deg2rad(pd.to_numeric(pts["era5_lat"], errors="coerce")))
    pts.loc[~np.isfinite(pts["grid_weight"]) | (pts["grid_weight"] <= 0), "grid_weight"] = np.nan

    keys = ["municipality_norm", "state_acronym_norm"]
    gdf_small = gdf_mun[keys + ["rep_lon", "rep_lat", "geometry"]].copy()

    try:
        joined = gpd.sjoin(
            pts,
            gdf_small[keys + ["geometry"]],
            how="inner",
            predicate="within",
        )
    except Exception as exc:
        print(f"[WARN] Spatial join failed: {exc}")
        print("[WARN] Falling back to nearest-grid extraction.")
        return aggregate_era5_to_municipalities_nearest(gdf_mun, ds)

    trend_vars = [v for v in vars_all if v.endswith("_trend_decade")]
    rows = []

    for name, g in joined.groupby(keys, dropna=False):
        w = pd.to_numeric(g["grid_weight"], errors="coerce").to_numpy(float)
        row = {
            "municipality_norm": name[0],
            "state_acronym_norm": name[1],
            "era5_integration_method": "zonal_gridpoint_coslat_weighted",
            "era5_n_gridpoints": int(len(g)),
            "era5_mean_lat": weighted_mean_values(g["era5_lat"], w),
            "era5_mean_lon": weighted_mean_values(g["era5_lon"], w),
        }

        for var in trend_vars:
            row[var] = weighted_mean_values(
                pd.to_numeric(g[var], errors="coerce").to_numpy(float),
                w,
            )

        tr = pd.to_numeric(g[DHW_COMMON_TREND_VAR], errors="coerce").to_numpy(float)
        pv = pd.to_numeric(g[DHW_COMMON_PVALUE_VAR], errors="coerce").to_numpy(float)
        valid = np.isfinite(tr) & np.isfinite(pv) & np.isfinite(w) & (w > 0)
        sigpos = valid & (tr > 0) & (pv <= P_THRESHOLD)
        row["DHW_TmaxOnly_significant_positive_fraction"] = (
            float(np.sum(w[sigpos]) / np.sum(w[valid]))
            if np.any(valid) else np.nan
        )
        rows.append(row)

    zonal = pd.DataFrame(rows)

    missing = (
        gdf_small[keys + ["rep_lon", "rep_lat"]]
        .merge(zonal[keys], on=keys, how="left", indicator=True)
        .query("_merge == 'left_only'")
        .drop(columns="_merge")
    )

    print(f"[INFO] Zonal ERA5 matched municipalities: {len(zonal)}")
    print(f"[INFO] Nearest-grid fallback municipalities: {len(missing)}")

    if len(missing) > 0:
        nearest = aggregate_era5_to_municipalities_nearest(
            gdf_small.merge(missing[keys], on=keys, how="inner"),
            ds,
        )
        return pd.concat([zonal, nearest], ignore_index=True)

    return zonal


def aggregate_era5_to_municipalities_nearest(gdf_mun, ds):
    lon = ds["lon"].values
    lat = ds["lat"].values

    if np.nanmax(lon) > 180:
        lon = ((lon + 180) % 360) - 180

    lon2d, lat2d = np.meshgrid(lon, lat)
    points = np.column_stack([lat2d.ravel(), lon2d.ravel()])
    tree = cKDTree(points)

    keys = ["municipality_norm", "state_acronym_norm"]

    out = gdf_mun[keys + ["rep_lon", "rep_lat"]].drop_duplicates().copy()
    ok = out["rep_lon"].notna() & out["rep_lat"].notna()

    query = np.column_stack([out.loc[ok, "rep_lat"].values, out.loc[ok, "rep_lon"].values])
    dist, idx = tree.query(query)

    out["era5_integration_method"] = "nearest_gridpoint_fallback"
    out["era5_n_gridpoints"] = 1
    out["era5_mean_lat"] = np.nan
    out["era5_mean_lon"] = np.nan
    out.loc[ok, "era5_mean_lat"] = points[idx, 0]
    out.loc[ok, "era5_mean_lon"] = points[idx, 1]
    out["era5_nearest_distance_deg"] = np.nan
    out.loc[ok, "era5_nearest_distance_deg"] = dist

    vars_all = [v for v in ds.data_vars if v.endswith("_trend_decade") or v.endswith("_pvalue")]

    for v in vars_all:
        arr = ds[v].values
        vals = np.full(len(out), np.nan)

        if ok.any():
            lat_idx = np.array([np.argmin(np.abs(lat - la)) for la in out.loc[ok, "era5_mean_lat"].values])
            lon_idx = np.array([np.argmin(np.abs(lon - lo)) for lo in out.loc[ok, "era5_mean_lon"].values])
            vals[ok.values] = arr[lat_idx, lon_idx]

        out[v] = vals

    tr = pd.to_numeric(out[DHW_COMMON_TREND_VAR], errors="coerce")
    pv = pd.to_numeric(out[DHW_COMMON_PVALUE_VAR], errors="coerce")
    valid = tr.notna() & pv.notna()
    out["DHW_TmaxOnly_significant_positive_fraction"] = np.where(
        valid,
        ((tr > 0) & (pv <= P_THRESHOLD)).astype(float),
        np.nan,
    )
    return out


def extract_era5_trends(mun_table, gdf):
    """
    Integrate Figure 01 fields to municipalities.

    The DHW–HHW contrast is read directly from the common-scale Figure 01
    contrast. Primary DHW and HHW regime-specific intensity fields are never
    subtracted in this workflow.
    """
    if not os.path.exists(ERA5_TRENDS_NC):
        raise FileNotFoundError(f"ERA5 trends file not found: {ERA5_TRENDS_NC}")

    print(f"[INFO] Reading Figure 01 trends: {ERA5_TRENDS_NC}")
    ds = safe_open_dataset(ERA5_TRENDS_NC, decode_times=False, chunks=None)

    required_source = [
        DRY_SHIFT_SOURCE_VAR,
        DHW_COMMON_TREND_VAR,
        HHW_COMMON_TREND_VAR,
        DHW_COMMON_PVALUE_VAR,
        "DHW_frequency_trend_decade",
        "DHW_duration_trend_decade",
    ]
    missing = [var for var in required_source if var not in ds.data_vars]
    if missing:
        ds.close()
        raise RuntimeError(
            "The supplied Figure 01 trend file is not compatible with "
            "Figure 02. Missing variables: " + ", ".join(missing)
        )

    era5_mun = aggregate_era5_to_municipalities_zonal(gdf, ds)

    out = mun_table.merge(
        era5_mun,
        on=["municipality_norm", "state_acronym_norm"],
        how="left",
    )

    # Preserve the historical dataframe/plotting alias, but source it directly
    # from the common-scale Figure 01 contrast.
    out[DRY_SHIFT_ALIAS] = pd.to_numeric(
        out[DRY_SHIFT_SOURCE_VAR],
        errors="coerce",
    )

    # Municipality hotspot criterion aligned with the Figure 1.
    # P-values are never averaged. Statistical support is the weighted fraction
    # of contributing ERA5 cells with positive significant DHW Tmax-only trends.
    dhw_common_trend = pd.to_numeric(out[DHW_COMMON_TREND_VAR], errors="coerce")
    sigpos_fraction = pd.to_numeric(
        out["DHW_TmaxOnly_significant_positive_fraction"],
        errors="coerce",
    )

    out["dry_hot_hotspot"] = (
        (out[DRY_SHIFT_ALIAS] > DRY_SHIFT_THRESHOLD)
        & (dhw_common_trend > 0)
        & (sigpos_fraction >= MUNICIPAL_SIGPOS_FRACTION_THRESHOLD)
    ).astype(int)

    out["dry_hot_hotspot_intensity"] = np.where(
        out["dry_hot_hotspot"] == 1,
        out[DRY_SHIFT_ALIAS],
        np.nan,
    )
    out["dry_shift_stipple"] = out["dry_hot_hotspot"].astype(bool)

    out_file = os.path.join(
        OUT_DIR,
        "figure_02_municipality_dhw_hhw_contrast_1990_2024.csv",
    )
    out.to_csv(out_file, index=False)

    print(f"[OK] Saved municipality table: {out_file}")
    print(
        "[INFO] Diagnostic hotspot criterion: DHW-HHW > "
        f"{DRY_SHIFT_THRESHOLD:.1f} {DRY_SHIFT_UNITS.replace('$', '')}; "
        f"DHW Tmax-only trend > 0; p <= {P_THRESHOLD:.2f}"
    )
    print(
        "[INFO] The >4 cutoff is retained as a diagnostic threshold for "
        "continuity and must be re-evaluated with the hotspot "
        "sensitivity workflow."
    )
    print(
        f"[INFO] Hotspot municipalities: "
        f"{int(out['dry_hot_hotspot'].sum())}/{len(out)}"
    )

    ds.close()
    return out

