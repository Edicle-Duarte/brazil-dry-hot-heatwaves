def add_rug(ax, x_obs, color="0.1"):
    x_obs = np.asarray(x_obs, dtype=float)
    x_obs = x_obs[np.isfinite(x_obs)]

    if x_obs.size == 0:
        return

    ymin, ymax = ax.get_ylim()
    y_rug = ymin + 0.03 * (ymax - ymin)

    if len(x_obs) > 1500:
        rng = np.random.default_rng(RANDOM_SEED)
        x_obs = rng.choice(x_obs, size=1500, replace=False)

    ax.plot(
        x_obs,
        np.full_like(x_obs, y_rug),
        "|",
        color=color,
        alpha=0.22,
        markersize=4,
        markeredgewidth=0.45,
        zorder=4,
    )


def plot_regional_gam(ax, res, region):
    color = "#D95F02"

    if res is None:
        ax.text(0.5, 0.5, "Insufficient data", transform=ax.transAxes,
                ha="center", va="center", fontsize=11)
        ax.set_title(region, fontsize=12, fontweight="bold")
        return

    ax.plot(res["x"], res["yhat"], color=color, linewidth=1.9)
    if np.isfinite(res["lo"]).any() and np.isfinite(res["hi"]).any():
        ax.fill_between(res["x"], res["lo"], res["hi"], color=color, alpha=0.20)

    ax.axhline(0, color="0.35", linestyle="--", linewidth=0.7)
    ax.grid(True, alpha=0.25, linewidth=0.35)
    method = res.get("method", "GAM spline")
    ax.set_title(f"{region} ({method})", fontsize=13, fontweight="bold")
    ax.tick_params(labelsize=12)

    add_rug(ax, res.get("x_obs", []), color=color)

    txt = f"N={res['n']}\nρw={res['rho']:.2f}\nΔ={res['delta_q4_q1']:.2f}"
    ax.text(
        0.04, 0.95, txt,
        transform=ax.transAxes,
        ha="left", va="top",
        fontsize=11,
        bbox=dict(facecolor="white", edgecolor="0.7", alpha=0.85),
    )


