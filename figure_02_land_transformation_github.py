def normalize_text(x):
    if pd.isna(x):
        return ""
    s = str(x).strip()
    s = unicodedata.normalize("NFKD", s)
    s = "".join(ch for ch in s if not unicodedata.combining(ch))
    s = s.upper()
    s = re.sub(r"\s+", " ", s)
    return s


def normalize_class(x):
    if pd.isna(x):
        return ""
    s = str(x).strip().lower()
    s = unicodedata.normalize("NFKD", s)
    s = "".join(ch for ch in s if not unicodedata.combining(ch))
    s = re.sub(r"\s+", " ", s)
    return s


def normalize_biome(x):
    s = normalize_text(x)
    mapping = {
        "AMAZONIA": "Amazônia",
        "CERRADO": "Cerrado",
        "CAATINGA": "Caatinga",
        "MATA ATLANTICA": "Mata Atlântica",
        "PAMPA": "Pampas",
        "PAMPAS": "Pampas",
        "PANTANAL": "Pantanal",
    }
    return mapping.get(s, str(x))


def detect_column(columns, candidates):
    norm_map = {normalize_text(c): c for c in columns}
    for cand in candidates:
        nc = normalize_text(cand)
        if nc in norm_map:
            return norm_map[nc]
    for col in columns:
        nc = normalize_text(col)
        for cand in candidates:
            if normalize_text(cand) in nc:
                return col
    return None


