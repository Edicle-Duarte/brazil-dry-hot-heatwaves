def safe_div(num, den):
    num = np.asarray(num, dtype=float)
    den = np.asarray(den, dtype=float)
    return np.where((den > 0) & np.isfinite(den), num / den, np.nan)


def weighted_mean_values(values, weights):
    values = np.asarray(values, dtype=float)
    weights = np.asarray(weights, dtype=float)
    ok = np.isfinite(values) & np.isfinite(weights) & (weights > 0)
    if not np.any(ok):
        return np.nan
    return float(np.average(values[ok], weights=weights[ok]))


def weighted_mean(g, value_col, weight_col="total_area_2024_ha"):
    return weighted_mean_values(
        pd.to_numeric(g[value_col], errors="coerce").values,
        pd.to_numeric(g[weight_col], errors="coerce").values
    )


def weighted_quantile(values, weights, q):
    values = np.asarray(values, dtype=float)
    weights = np.asarray(weights, dtype=float)
    ok = np.isfinite(values) & np.isfinite(weights) & (weights > 0)
    if not np.any(ok):
        return np.nan
    values = values[ok]
    weights = weights[ok]
    order = np.argsort(values)
    values = values[order]
    weights = weights[order]
    cdf = np.cumsum(weights) / np.sum(weights)
    return float(values[np.searchsorted(cdf, q)])


def _weighted_pearson_core(x, y, w):
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    w = np.asarray(w, dtype=float)
    ok = np.isfinite(x) & np.isfinite(y) & np.isfinite(w) & (w > 0)
    if ok.sum() < 3:
        return np.nan
    x, y, w = x[ok], y[ok], w[ok]
    mx = np.average(x, weights=w)
    my = np.average(y, weights=w)
    cov = np.average((x - mx) * (y - my), weights=w)
    vx = np.average((x - mx) ** 2, weights=w)
    vy = np.average((y - my) ** 2, weights=w)
    if vx <= 0 or vy <= 0:
        return np.nan
    return float(cov / np.sqrt(vx * vy))


def weighted_spearman(x, y, w, n_perm=N_PERM, seed=RANDOM_SEED):
    """Area-weighted Spearman rho with a two-sided permutation p-value."""
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)
    w = np.asarray(w, dtype=float)
    ok = np.isfinite(x) & np.isfinite(y) & np.isfinite(w) & (w > 0)
    if ok.sum() < 10:
        return np.nan, np.nan
    x, y, w = x[ok], y[ok], w[ok]
    xr = stats.rankdata(x)
    yr = stats.rankdata(y)
    rho = _weighted_pearson_core(xr, yr, w)
    if not np.isfinite(rho):
        return np.nan, np.nan
    rng = np.random.default_rng(seed)
    exceed = 0
    for _ in range(int(n_perm)):
        rp = _weighted_pearson_core(xr, rng.permutation(yr), w)
        if np.isfinite(rp) and abs(rp) >= abs(rho):
            exceed += 1
    p = (exceed + 1.0) / (int(n_perm) + 1.0)
    return float(rho), float(p)


