def prepare_gam_data(mun_table, x_col, y_col, region=None):
    cols = [x_col, y_col, "focus_region", "total_area_2024_ha"]
    df = mun_table[cols].copy()

    if region is not None:
        df = df[df["focus_region"] == region].copy()
    else:
        df = df[df["focus_region"].isin(REGION_ORDER)].copy()

    df[x_col] = pd.to_numeric(df[x_col], errors="coerce")
    df[y_col] = pd.to_numeric(df[y_col], errors="coerce")
    df["total_area_2024_ha"] = pd.to_numeric(df["total_area_2024_ha"], errors="coerce")

    df = df.dropna(subset=[x_col, y_col, "focus_region", "total_area_2024_ha"])
    df = df[df["total_area_2024_ha"] > 0].copy()

    if len(df) < 10:
        return df

    # Fit domain is restricted to the 1st–99th percentile range.
    q01, q99 = np.nanpercentile(df[x_col], [1, 99])
    df = df[(df[x_col] >= q01) & (df[x_col] <= q99)].copy()

    w = np.sqrt(df["total_area_2024_ha"].values)
    df["gam_weight"] = w / np.nanmean(w)

    return df


def build_design_matrix(df, x_col, design_info=None):
    data = df[[x_col]].copy()
    data = data.rename(columns={x_col: "x"})

    formula = f"bs(x, df={SPLINE_DF}, degree=3, include_intercept=False)"

    if design_info is None:
        X = dmatrix(formula, data=data, return_type="dataframe")
        return X, X.design_info

    X = dmatrix(design_info, data=data, return_type="dataframe")
    return X, design_info


def fit_spline_model(df_fit, x_col, y_col):
    if len(df_fit) < MIN_N_FOR_GAM:
        return None

    unique_x = np.unique(np.round(df_fit[x_col].values, 6))
    if len(unique_x) <= SPLINE_DF + 2:
        X = sm.add_constant(df_fit[[x_col]])
        y = df_fit[y_col].values
        w = df_fit["gam_weight"].values
        fit = sm.WLS(y, X, weights=w).fit(cov_type="HC3")
        return {
            "fit": fit,
            "design_info": None,
            "x_col": x_col,
            "y_col": y_col,
            "linear": True,
        }

    X, design_info = build_design_matrix(df_fit, x_col)
    y = df_fit[y_col].values
    w = df_fit["gam_weight"].values

    model = sm.WLS(y, X, weights=w)
    fit = model.fit(cov_type="HC3")

    return {
        "fit": fit,
        "design_info": design_info,
        "x_col": x_col,
        "y_col": y_col,
        "linear": False,
    }


def predict_curve(model_info, x_grid):
    fit = model_info["fit"]
    x_col = model_info["x_col"]

    pred_df = pd.DataFrame({x_col: x_grid})

    if model_info.get("linear", False):
        Xp = sm.add_constant(pred_df[[x_col]], has_constant="add")
        return np.asarray(fit.predict(Xp), dtype=float)

    Xp, _ = build_design_matrix(pred_df, x_col, model_info["design_info"])
    return np.asarray(fit.predict(Xp), dtype=float)


def bootstrap_spline_curve(df_fit, x_col, y_col, x_grid):
    base = fit_spline_model(df_fit, x_col, y_col)
    if base is None:
        return None

    yhat = predict_curve(base, x_grid)

    rng = np.random.default_rng(RANDOM_SEED)
    boot = []

    for _ in range(N_BOOT):
        idx = rng.integers(0, len(df_fit), size=len(df_fit))
        db = df_fit.iloc[idx].copy()

        try:
            model_b = fit_spline_model(db, x_col, y_col)
            if model_b is None:
                continue
            yb = predict_curve(model_b, x_grid)
            if np.all(np.isfinite(yb)):
                boot.append(yb)
        except Exception:
            continue

    if len(boot) >= 20:
        boot = np.vstack(boot)
        lo = np.nanpercentile(boot, 2.5, axis=0)
        hi = np.nanpercentile(boot, 97.5, axis=0)
    else:
        lo = np.full_like(yhat, np.nan)
        hi = np.full_like(yhat, np.nan)

    rho, p = weighted_spearman(
        df_fit[x_col].values,
        df_fit[y_col].values,
        df_fit["gam_weight"].values,
    )

    q25 = np.nanpercentile(df_fit[x_col], 25)
    q75 = np.nanpercentile(df_fit[x_col], 75)

    low = df_fit[df_fit[x_col] <= q25][y_col].dropna()
    high = df_fit[df_fit[x_col] >= q75][y_col].dropna()

    delta = float(np.nanmedian(high) - np.nanmedian(low)) if len(low) >= 10 and len(high) >= 10 else np.nan

    return {
        "x": x_grid,
        "yhat": yhat,
        "lo": lo,
        "hi": hi,
        "n": len(df_fit),
        "rho": rho,
        "p": p,
        "delta_q4_q1": delta,
        "x_obs": df_fit[x_col].values,
    }


def bootstrap_lowess_curve(df_fit, x_col, y_col, x_grid, frac=0.70):
    """
    LOWESS smoother for heterogeneous urban signal.
    Used for Sudeste urbano to avoid unstable spline edge behaviour.
    LOWESS in statsmodels is unweighted; area weights are retained for summary
    diagnostics, but the smoother is intentionally descriptive.
    """
    if len(df_fit) < MIN_N_FOR_GAM:
        return None

    x = np.asarray(df_fit[x_col].values, dtype=float)
    y = np.asarray(df_fit[y_col].values, dtype=float)

    ok = np.isfinite(x) & np.isfinite(y)
    x = x[ok]
    y = y[ok]

    if len(x) < MIN_N_FOR_GAM:
        return None

    order = np.argsort(x)
    x_sorted = x[order]
    y_sorted = y[order]

    fit = lowess(y_sorted, x_sorted, frac=frac, it=1, return_sorted=True)
    # Remove duplicate x values before interpolation.
    xu, idx = np.unique(fit[:, 0], return_index=True)
    yu = fit[:, 1][idx]
    yhat = np.interp(x_grid, xu, yu)

    rng = np.random.default_rng(RANDOM_SEED)
    boot = []

    for _ in range(N_BOOT):
        idxb = rng.integers(0, len(x), size=len(x))
        xb = x[idxb]
        yb = y[idxb]
        try:
            order_b = np.argsort(xb)
            fb = lowess(yb[order_b], xb[order_b], frac=frac, it=1, return_sorted=True)
            xbu, ib = np.unique(fb[:, 0], return_index=True)
            ybu = fb[:, 1][ib]
            if len(xbu) >= 3:
                boot.append(np.interp(x_grid, xbu, ybu))
        except Exception:
            continue

    if len(boot) >= 20:
        boot = np.vstack(boot)
        lo = np.nanpercentile(boot, 2.5, axis=0)
        hi = np.nanpercentile(boot, 97.5, axis=0)
    else:
        lo = np.full_like(yhat, np.nan)
        hi = np.full_like(yhat, np.nan)

    rho, p = weighted_spearman(
        df_fit[x_col].values,
        df_fit[y_col].values,
        df_fit["gam_weight"].values,
    )

    q25 = np.nanpercentile(df_fit[x_col], 25)
    q75 = np.nanpercentile(df_fit[x_col], 75)
    low_q = df_fit[df_fit[x_col] <= q25][y_col].dropna()
    high_q = df_fit[df_fit[x_col] >= q75][y_col].dropna()
    delta = float(np.nanmedian(high_q) - np.nanmedian(low_q)) if len(low_q) >= 10 and len(high_q) >= 10 else np.nan

    return {
        "x": x_grid,
        "yhat": yhat,
        "lo": lo,
        "hi": hi,
        "n": len(df_fit),
        "rho": rho,
        "p": p,
        "delta_q4_q1": delta,
        "x_obs": df_fit[x_col].values,
        "method": "LOWESS",
    }


def run_regional_gam_models(mun_table):
    results = {}

    for region in GAM_REGIONS:
        df_fit = prepare_gam_data(
            mun_table,
            "transformed_non_native_pct_2024",
            "dry_minus_humid_intensity_trend",
            region=region
        )

        if len(df_fit) < MIN_N_FOR_GAM:
            print(f"[WARN] Insufficient data for regional GAM {region}: N={len(df_fit)}")
            results[region] = None
            continue

        # Use 1st–99th percentile for prediction domain.
        x = df_fit["transformed_non_native_pct_2024"].values
        q01, q99 = np.nanpercentile(x, [1, 99])
        x_grid = np.linspace(q01, q99, 300)

        if region == "Sudeste urbano":
            print(f"[INFO] Fitting regional LOWESS: {region}, N={len(df_fit)}")
            results[region] = bootstrap_lowess_curve(
                df_fit,
                "transformed_non_native_pct_2024",
                "dry_minus_humid_intensity_trend",
                x_grid,
                frac=0.70,
            )
        else:
            print(f"[INFO] Fitting regional GAM-like spline: {region}, N={len(df_fit)}, df={SPLINE_DF}")
            results[region] = bootstrap_spline_curve(
                df_fit,
                "transformed_non_native_pct_2024",
                "dry_minus_humid_intensity_trend",
                x_grid
            )
            if results[region] is not None:
                results[region]["method"] = "GAM spline"

    rows = []
    for region, res in results.items():
        if res is None:
            continue
        rows.append({
            "region": region,
            "n": res["n"],
            "weighted_spearman_rho": res["rho"],
            "weighted_spearman_p_permutation": res["p"],
            "delta_Q4_minus_Q1": res["delta_q4_q1"],
            "method": res.get("method", "GAM spline"),
            "spline_df": SPLINE_DF if res.get("method", "GAM spline") != "LOWESS" else np.nan,
            "n_bootstrap": N_BOOT,
            "n_permutations": N_PERM,
            "prediction_domain": "x 1st-99th percentile",
        })

    out = pd.DataFrame(rows)
    out_file = os.path.join(OUT_DIR, "figure_02_regional_model_summary_dhw_hhw_contrast_1990_2024.csv")
    out.to_csv(out_file, index=False)
    print(f"[OK] Saved regional GAM summary: {out_file}")

    return results


