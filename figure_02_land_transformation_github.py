def _weighted_summary(g, col):
    values = pd.to_numeric(g[col], errors="coerce").to_numpy(float)
    weights = pd.to_numeric(g["total_area_2024_ha"], errors="coerce").to_numpy(float)
    q25 = weighted_quantile(values, weights, 0.25)
    q50 = weighted_quantile(values, weights, 0.50)
